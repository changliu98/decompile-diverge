/* Direct-call crash harness for CVE-2023-45897 (exfatprogs, read_file_dentry_set).
 *
 * Real bug (fsck/fsck.c): read_file_dentry_set() allocates the inode name buffer
 * via exfat_alloc_inode(), which calloc()s exactly
 *
 *     offsetof(struct exfat_inode, name) + NAME_BUFFER_SIZE
 *         == offsetof(...) + (EXFAT_NAME_MAX + 1) * 2   ==  256 * 2 == 512 bytes
 *         == 256 __le16 ("name[0]") slots.
 *
 * It then loops over the file dentry's secondary-count field, `file_de->file_num_ext`
 * (an on-disk __u8, attacker-controlled, range 0..255), copying ENTRY_NAME_MAX (15)
 * __le16 units (30 bytes) per iteration into that fixed 256-slot buffer with NO bound
 * check against file_num_ext:
 *
 *     for (i = 2; i <= file_de->file_num_ext; i++) {
 *         ...
 *         memcpy(node->name + (i - 2) * ENTRY_NAME_MAX, dentry->name_unicode,
 *                sizeof(dentry->name_unicode));
 *     }
 *
 * Once (i - 2) * 15 + 15 > 256, i.e. once i >= 19, that memcpy writes past the end
 * of the heap-allocated node->name buffer: a heap-buffer-overflow WRITE, CWE-787,
 * entirely INSIDE read_file_dentry_set (matches the frozen baseline dedup_token
 * "__asan_memcpy--read_file_dentry_set--read_file" / bug_class "heap-buffer-overflow"
 * / access "WRITE").
 *
 * This harness calls read_file_dentry_set() DIRECTLY. Its real caller walks an
 * on-disk directory via `struct exfat_de_iter`, a disk-block read-ahead cache; the
 * TARGET FUNCTION (and its real sibling helper file_calc_checksum(), also embedded
 * verbatim below) never touch that struct's fields directly -- they only ever call
 * exfat_de_iter_get()/exfat_de_iter_get_dirty() on it, which in the real
 * implementation (lib/exfat_dir.c) boils down to returning a pointer into a linear
 * buffer of on-disk 32-byte `struct exfat_dentry` records at index `ith`:
 *
 *     *dentry = (struct exfat_dentry *)(iter->buffer_desc[block & 0x01].buffer +
 *                next_de_file_offset % iter->read_size);
 *     return 0;   // (or an error if `ith` is out of range)
 *
 * so this harness replaces the disk-cluster cache (irrelevant to the vulnerability)
 * with the exact same final view: `struct exfat_de_iter` here is just {dentries,
 * n_dentries} over a directly-addressable array of dentries carved straight out of
 * the attacker-controlled HEAP buffer read from argv[1].
 *
 * Input format: a flat array of 32-byte struct exfat_dentry records (exactly the
 * on-disk exFAT directory-entry layout), starting at file offset 0:
 *   [0]      file dentry   (type=EXFAT_FILE, num_ext=N, checksum=<matching CRC>)
 *   [1]      stream dentry (type=EXFAT_STREAM)
 *   [2..N]   name dentries (type=EXFAT_NAME, 15 UTF-16LE code units of name data)
 * i.e. exactly what a real exFAT file's dentry set looks like on disk; `io/input/0`
 * and the rest of the corpus are generated by gen_corpus.py (kept beside this file).
 */

