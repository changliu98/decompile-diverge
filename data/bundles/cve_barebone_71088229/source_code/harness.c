#define EXFAT_DELETE            ~(0x80)
#define EXFAT_FILE               0x85  /* file or dir */
#define EXFAT_STREAM             0xC0  /* stream entry */
#define EXFAT_NAME                0xC1  /* file name entry */

#define VOLUME_LABEL_MAX_LEN    11
#define VOLUME_GUID_LEN         16
#define ENTRY_NAME_MAX          15

#define EXFAT_NAME_MAX          255
#define NAME_BUFFER_SIZE        ((EXFAT_NAME_MAX + 1) * 2)

#define EXFAT_SF_CONTIGUOUS     0x02

/* fsck/repair.h error codes referenced by read_file_dentry_set()'s
 * repair_file_ask() calls (verbatim values; the macro below never actually
 * evaluates them, but they are defined for faithfulness/readability). */
#define ER_DE_CHECKSUM          0x00001001
#define ER_DE_SECONDARY_COUNT   0x00001011
#define ER_DE_STREAM            0x00001020
#define ER_DE_NAME              0x00001030
#define ER_FILE_VALID_SIZE      0x00002001

struct exfat_dentry {
	__u8 type;
	union {
		struct {
			__u8 character_count;
			__le16 volume_label[VOLUME_LABEL_MAX_LEN];
			__u8 reserved[8];
		} __attribute__((packed)) vol; /* file directory entry */

		struct {
			__u8 num_ext;
			__le16 checksum;
			__le16 attr;
			__le16 reserved1;
			__le16 create_time;
			__le16 create_date;
			__le16 modify_time;
			__le16 modify_date;
			__le16 access_time;
			__le16 access_date;
			__u8 create_time_ms;
			__u8 modify_time_ms;
			__u8 create_tz;
			__u8 modify_tz;
			__u8 access_tz;
			__u8 reserved2[7];
		} __attribute__((packed)) file; /* file directory entry */
		struct {
			__u8 flags;
			__u8 reserved1;
			__u8 name_len;
			__le16 name_hash;
			__le16 reserved2;
			__le64 valid_size;
			__le32 reserved3;
			__le32 start_clu;
			__le64 size;
		} __attribute__((packed)) stream; /* stream extension directory entry */
		struct {
			__u8 flags;
			__le16 unicode_0_14[15];
		} __attribute__((packed)) name; /* file name directory entry */
		struct {
			__u8 flags;
			__u8 reserved[18];
			__le32 start_clu;
			__le64 size;
		} __attribute__((packed)) bitmap; /* allocation bitmap directory entry */
		struct {
			__u8 reserved1[3];
			__le32 checksum;
			__u8 reserved2[12];
			__le32 start_clu;
			__le64 size;
		} __attribute__((packed)) upcase; /* up-case table directory entry */
		struct {
			__u8 num_ext;
			__le16 checksum;
			__u16 flags;
			__u8 guid[VOLUME_GUID_LEN];
			__u8 reserved[10];
		} __attribute__((packed)) guid; /* volume GUID directory entry */
	} __attribute__((packed)) dentry;
} __attribute__((packed));

