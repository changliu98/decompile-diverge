static void exfat_err(const char *fmt, ...);

/* lib/exfat_fs.c: exfat_alloc_inode / exfat_free_inode, verbatim (these are the
 * REAL heap allocator for node->name -- the buffer whose overflow this harness
 * exercises). */
static struct exfat_inode *exfat_alloc_inode(__u16 attr)
{
	struct exfat_inode *node;
	int size;

	size = offsetof(struct exfat_inode, name) + NAME_BUFFER_SIZE;
	node = (struct exfat_inode *)calloc(1, size);
	if (!node) {
		exfat_err("failed to allocate exfat_node\n");
		return NULL;
	}

	node->parent = NULL;
	INIT_LIST_HEAD(&node->children);
	INIT_LIST_HEAD(&node->sibling);
	INIT_LIST_HEAD(&node->list);

	node->attr = attr;
	return node;
}

static void exfat_free_inode(struct exfat_inode *node)
{
	if (node) {
		if (node->dentry_set)
			free(node->dentry_set);
		free(node);
	}
}

/* lib/exfat_dir.c: exfat_calc_dentry_checksum, verbatim (real callee of
 * file_calc_checksum() below). */
static void exfat_calc_dentry_checksum(struct exfat_dentry *dentry,
				uint16_t *checksum, bool primary)
{
	unsigned int i;
	uint8_t *bytes;

	bytes = (uint8_t *)dentry;

	/* use += to avoid promotion to int; UBSan complaints about signed overflow */
	*checksum = (*checksum << 15) | (*checksum >> 1);
	*checksum += bytes[0];
	*checksum = (*checksum << 15) | (*checksum >> 1);
	*checksum += bytes[1];

	i = primary ? 4 : 2;
	for (; i < sizeof(*dentry); i++) {
		*checksum = (*checksum << 15) | (*checksum >> 1);
		*checksum += bytes[i];
	}
}

/* ==================================================================== *
 * Harness-only driver plumbing (NOT part of the vulnerable code): a
 * minimal, behaviorally-equivalent stand-in for the disk-backed
 * exfat_de_iter described in the file header above, plus no-op stubs for
 * the fsck-UI/lookup helpers that read_file_dentry_set() calls on error
 * paths this harness's crafted inputs never take (checksum always
 * matches, num_ext>=2, stream dentry always present -- see gen_corpus.py).
 * ==================================================================== */

struct exfat_de_iter {
	struct exfat_dentry *dentries;
	size_t n_dentries;
};

static int exfat_de_iter_get(struct exfat_de_iter *iter, int ith,
			      struct exfat_dentry **dentry)
{
	if (ith < 0 || (size_t)ith >= iter->n_dentries)
		return EOF;
	*dentry = &iter->dentries[ith];
	return 0;
}

static int exfat_de_iter_get_dirty(struct exfat_de_iter *iter, int ith,
				    struct exfat_dentry **dentry)
{
	return exfat_de_iter_get(iter, ith, dentry);
}

