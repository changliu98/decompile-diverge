/* BYOH memstate harness for the github functional axis (coreutils manifest).
 *
 * TARGET SIGNATURE:
 *   enum strtol_error human_options(char const *spec, int *opts, uintmax_t *block_size)
 *   -- lib/human.c (gnulib, vendored by coreutils). main_c = the WHOLE lib/human.c file
 *   (func.c), so humblock()/default_block_size() (its unchanged, unspliced callees, defined
 *   lower in the SAME file) are already present -- no companion .c needed for those two.
 *
 * WHY spec IS FIXED TO NULL:
 *   humblock()'s non-NULL-spec branch calls ARGMATCH(spec,...)/xstrtoumax(...). Those are
 *   declared in lib/argmatch.h / lib/xstrtol.h (both in headers_resolved) but DEFINED in
 *   lib/argmatch.c / lib/xstrtol.c -- outside this manifest entry's main_c. Because main_c is
 *   compiled as ONE translation unit, humblock()'s compiled body references those symbols
 *   UNCONDITIONALLY (link-time), even though this harness only ever calls human_options with
 *   spec==NULL (so that branch is dead at RUNTIME). Trivial, never-invoked link-satisfying
 *   stand-ins are supplied below (companions, not func0 -- human_options is the ONLY spliced
 *   function). A SEPARATE, orthogonal problem: lib/argmatch.h unconditionally
 *   `#include <stdcountof.h>`, a C23 header this toolchain's clang lacks (verified: `fatal
 *   error: 'stdcountof.h' file not found`) -- so its inclusion (transitively pulled in by
 *   human.c) is pre-empted below by defining its own header guard (ARGMATCH_H_) before
 *   func.c is pulled in, and providing just the ARGMATCH macro + argmatch() prototype human.c
 *   actually needs ourselves (mirrors the `#define GNULIB_XALLOC 1` pre-func.c trick used by
 *   the base_name harness for a similar transitively-defined-elsewhere gnulib symbol).
 *
 * FIXED SETUP for determinism: BLOCK_SIZE / BLOCKSIZE / POSIXLY_CORRECT are explicitly
 * unset before the call (humblock()/default_block_size() consult them via getenv) so the
 * result never depends on the ambient environment.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim), with a
 * small pre-PRELUDE header-guard/prototype block and the two dead-but-linkable companion
 * definitions above MAIN_OPEN (harness-only scaffolding, never touched by the splice).
 * Contract: build spec (fixed NULL) and the two OUTPUT-only scalars, call human_options,
 * fold its RETURN VALUE plus the CONTENT written through the opts and block_size out-params
 * (never an address) into vb_digest via vb_mix, then vb_dump(argv[2]) & exit 0. */

