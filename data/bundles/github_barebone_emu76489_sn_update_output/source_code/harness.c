  sng.base_count   = (uint32_t)vb_int();
  sng.noise_seed   = (uint32_t)vb_int();
  sng.noise_mode   = (uint32_t)(vb_take(1) & 1);
  sng.noise_fref   = (uint32_t)(vb_take(1) & 1);
  sng.noise_count  = (uint32_t)vb_int();
  sng.noise_freq   = (uint32_t)vb_int();
  sng.noise_volume = (uint32_t)(vb_take(1) % 16);      /* voltbl[16] index -- must stay in range */

