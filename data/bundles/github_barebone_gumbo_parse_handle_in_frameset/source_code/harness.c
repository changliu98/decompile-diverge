/* Recursive structural fold of the parsed tree -- type/tag/attr-count/child-count/text content
 * for every node, never a pointer value. Local-only state (recursion via the call stack), so it
 * has no effect on the dumped .data/.bss beyond what it feeds into vb_digest. */
static void vb_fold_node(const GumboNode *node, int depth) {
  if (!node || depth > 64) return;
  long t = (long)node->type;
  vb_mix(&t, sizeof t);
  const GumboVector *kids = NULL;
  if (node->type == GUMBO_NODE_ELEMENT || node->type == GUMBO_NODE_TEMPLATE) {
    long tag = (long)node->v.element.tag;         vb_mix(&tag, sizeof tag);
    long ns  = (long)node->v.element.tag_namespace; vb_mix(&ns, sizeof ns);
    long na  = (long)node->v.element.attributes.length; vb_mix(&na, sizeof na);
    kids = &node->v.element.children;
  } else if (node->type == GUMBO_NODE_DOCUMENT) {
    kids = &node->v.document.children;
  } else {
    /* TEXT / CDATA / COMMENT / WHITESPACE: fold the decoded text content. */
    vb_mix_s(node->v.text.text);
  }
  if (kids) {
    long n = (long)kids->length;
    vb_mix(&n, sizeof n);
    for (unsigned int _i = 0; _i < kids->length; _i++) {
      vb_fold_node((const GumboNode *)kids->data[_i], depth + 1);
    }
  }
}

