  int prev_len  = (pl_pick == 0) ? 0 : (pl_pick == 1 ? VT_N0 : VT_N1);
  vt_f.previous_length = prev_len;
  vt_f.samples_output  = (unsigned int)vb_take(1);   /* pre-existing running total */

  float cbuf[VT_CH][VT_CAP];
  float pwin[VT_CH][VT_CAP];
  for (c = 0; c < VT_CH; c++) {
    for (k = 0; k < VT_CAP; k++) cbuf[c][k] = ((float)(int)vb_take(1) - 128.0f) / 16.0f;
    for (k = 0; k < VT_CAP; k++) pwin[c][k] = ((float)(int)vb_take(1) - 128.0f) / 16.0f;
    vt_f.channel_buffers[c] = cbuf[c];
    vt_f.previous_window[c] = pwin[c];
  }

