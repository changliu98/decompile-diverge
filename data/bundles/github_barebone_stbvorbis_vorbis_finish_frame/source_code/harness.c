  stb_vorbis vt_f; memset(&vt_f, 0, sizeof vt_f);
  vt_f.channels    = VT_CH;
  vt_f.blocksize_0 = 2 * VT_N0;   /* get_window(n) does `n<<1`, so n==VT_N0 hits this */
  vt_f.blocksize_1 = 2 * VT_N1;   /* and n==VT_N1 hits this */

  int k, c;
  float win0[VT_N0], win1[VT_N1];
  for (k = 0; k < VT_N0; k++) win0[k] = ((float)(int)vb_take(1) - 128.0f) / 16.0f;
  for (k = 0; k < VT_N1; k++) win1[k] = ((float)(int)vb_take(1) - 128.0f) / 16.0f;
  vt_f.window[0] = win0;
  vt_f.window[1] = win1;

