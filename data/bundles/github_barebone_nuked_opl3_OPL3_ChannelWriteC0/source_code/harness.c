/* BYOH memstate harness for the github functional axis (recompile-pool promotion).
 *
 * TARGET SIGNATURE:
 *   static void OPL3_ChannelWriteC0(opl3_channel *channel, uint8_t data)
 *
 * WHY HAND-WRITTEN: `opl3_channel *channel` is a pointer to a struct (opl3.h) whose
 * fields (chip/pair/slotz) must be wired up by the library's own constructor before the
 * target's call graph is safe to invoke -- funcharness's automatic signature parser only
 * knows int/float/char-string/T-array params, so this is UnsupportedSignature for the
 * generator (same reason as the sibling OPL3_ChannelSet4Op harness in this directory).
 *
 * OPL3_ChannelWriteC0(channel, data) itself dereferences `channel->chip->newm` directly,
 * and calls OPL3_ChannelUpdateAlg(channel), whose call graph (-> OPL3_ChannelSetupAlg)
 * dereferences channel->slotz[0]/[1] and channel->chip. A zero-initialised channel would
 * have all of those NULL and SEGV. So we call the library's OWN constructor, OPL3_Reset()
 * (same TU, untouched by the splice -- only OPL3_ChannelWriteC0's body is ever replaced),
 * to wire up every channel's chip/pair/slotz/out pointers exactly as a real chip does.
 *
 * `channel->pair` is NEVER dereferenced for this target: OPL3_Reset sets chtype=ch_2op for
 * every channel and OPL3_ChannelWriteC0 never writes chtype, so it stays ch_2op; inside
 * OPL3_ChannelUpdateAlg that means channel->alg = channel->con, and channel->con is always
 * `data & 0x01` (i.e. 0 or 1) -- so channel->alg never has bit 0x04 or 0x08 set, and
 * OPL3_ChannelSetupAlg always takes the plain (non-4op) `switch(channel->alg & 0x01)`
 * branch, which touches only `channel->slotz[0/1]->mod` and `channel->out[0..3]`
 * (pointers already valid from Reset) -- `channel->pair` is read only in the ch_4op /
 * ch_4op2 branches, which are unreachable here. So any channel index 0..17 is safe for any
 * (newm, data) combination.
 *
 * OPL3_ChannelWriteC0's own DIRECT writes are all plain scalar fields on the target
 * channel: fb, con, alg (via OPL3_ChannelUpdateAlg), cha, chb, chc, chd -- never a pointer.
 * We drive `data` and `chip.newm` (the mode flag branched on both directly in the target
 * and inside OPL3_ChannelUpdateAlg) from the seed, plus the channel index, call the
 * target, then fold the CONTENT of those 7 scalar fields into vb_digest. That captures the
 * function's complete observable effect while NEVER folding a pointer (slotz/out/pair/chip
 * addresses into the local `chip` are stack-relative and NOT stable across independently-
 * linked binaries -- folding them would masquerade as a false vanish). A no-op (stub) body
 * leaves fb=con=alg=chd=chc=0 and cha=chb=0xffff (whatever OPL3_Reset left them at)
 * regardless of `data`/`newm` -- so any seed whose `data` byte is nonzero (~255/256 of
 * them) diverges from that constant state under the real function, discriminating
 * identity from stub.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
