/* BYOH memstate harness for the github functional axis (recompile-pool promotion).
 *
 * TARGET SIGNATURE:
 *   static int read_image(gd_GIF *gif)
 *
 * WHY HAND-WRITTEN: `gd_GIF *gif` is a pointer to a STRUCT carrying STATEFUL context --
 * read_image reads raw bytes from `gif->fd` via POSIX read()/lseek(), and its own
 * precondition (`gif->fx < gif->width && gif->fy < gif->height`, both read FROM the fd)
 * couples the fd's byte CONTENT to the width/height fields elsewhere in the same struct.
 * The auto harness only knows int/float/string/T-array params and allocates each pointer
 * arg independently -- it cannot construct "an open, positioned fd whose next bytes are a
 * well-formed GIF Image Descriptor consistent with a pre-set width/height", so this is
 * UnsupportedSignature for the generator. We build that fd (an unlinked, memory-backed
 * temp file) and its exact byte layout ourselves, entirely deterministically from the
 * seed, so every call is in-contract.
 *
 * To keep the synthetic "file" always well-formed while staying clear of read_image's
 * OWN callee read_image_data() -- a much hairier LZW image-DATA decoder, a different and
 * more failure-prone code path we are not trying to exercise here -- the descriptor's
 * final byte is a fixed LZW "key size" of 0, which is < 2 and therefore INVALID: per
 * read_image_data's own contract this makes it return -1 immediately, having read
 * exactly one more byte -- no further reads, and gif->frame (which we never allocate) is
 * never touched. Every other descriptor field (fx, fy, fw, fh, the flags byte, and --
 * when the Local-Color-Table flag is set -- the LCT color bytes) is still genuinely
 * exercised and folded, so the differential covers the bulk of read_image's own body.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
/* auto-generated by ddiv.funcharness -- DO NOT EDIT */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include "func.c"

/* ---- program-exit memstate capture (see ddiv/functional.py) -----------------
 * Run func0 on a SAFE seed, fold its return value + any output buffers into a global
 * digest, then dump the program's own writable globals -- [.data, .bss], the part of
 * "all memory at program exit" that is deterministic across two independently-linked
 * binaries -- to argv[2]. The oracle byte-compares this dump to the frozen baseline:
 * equal => INTACT, differ-without-crash => silent VANISH, sanitizer/abort => DEVIATED. */

extern char __data_start[], _edata[], __bss_start[], _end[];

#define VB_MAXLEN   16     /* array length bound (paired T* arr, int n) */
#define VB_STRLEN   24     /* string length bound */
#define VB_INTBOUND 1000   /* scalar int magnitude bound */
#define VB_ARRLEN   8      /* default folded prefix for a lone array/pointer param */
#define VB_ARRCAP   256    /* generous zeroed allocation for a lone array/pointer param --
                            * modest over-reads by the original land on deterministic zeros;
                            * a read past the cap traps on the ORIGINAL build and the case is
                            * dropped by the safety/determinism filter (never a wrong verdict). */

static const unsigned char *VB_CUR; static long VB_N, VB_I;
static unsigned long vb_take(int nb){ unsigned long v=0; int k;
  for(k=0;k<nb;k++){ v |= (unsigned long)(VB_I<VB_N?VB_CUR[VB_I]:0) << (8*k); VB_I++; } return v; }
static long vb_int(void){ long m=2L*VB_INTBOUND+1; return (long)(vb_take(4)%m) - VB_INTBOUND; }
static double vb_dbl(void){ long x=(long)(vb_take(4)% (2000001UL)) - 1000000L; return (double)x/1000.0; }
static int vb_len(int bound){ return (int)(vb_take(1) % (unsigned)(bound+1)); }

/* result digest -- a global (lives in .data), so it is part of the dumped memstate.
 * FNV-1a over the function's return value + output buffers. */
static uint64_t vb_digest = 1469598103934665603ULL;
static void vb_mix(const void *p, unsigned long n){
  const unsigned char *b=(const unsigned char*)p; unsigned long i;
  for(i=0;i<n;i++){ vb_digest ^= b[i]; vb_digest *= 1099511628211ULL; } }
/* quantise a double to fixed-point (~1e-6 tolerance) so a numerically-equal result that
 * differs in the low mantissa bits (FMA / instruction-selection) still compares equal. */
static void vb_mix_d(double x){ long q;
  if(isnan(x)) q = (long)0x7ff8000000000000LL;
  else if(isinf(x)) q = (x>0?1:-1)*0x7fffffffffffffffLL;
  else q = (long)llround(x*1e6);
  vb_mix(&q, sizeof q); }
static void vb_mix_s(const char *s){
  if(!s){ unsigned char z=0; vb_mix(&z,1); return; }
  unsigned char nz=1; vb_mix(&nz,1); vb_mix(s, (unsigned long)strlen(s)); }

/* dump the program's writable globals (the deterministic part of the exit memstate). */
static void vb_dump(const char *path){
  VB_CUR=0; VB_N=0; VB_I=0;                  /* zero bookkeeping (VB_CUR holds a heap ptr) */
  if(!path) return;
  FILE *out = fopen(path, "wb"); if(!out) return;
  fwrite(__data_start, 1, (size_t)((char*)_edata   - (char*)__data_start), out);
  fwrite(__bss_start,  1, (size_t)((char*)_end     - (char*)__bss_start),  out);
  fclose(out); }

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* Zero-init the whole struct up front: no field we don't explicitly set (canvas, frame,
   * gct, callbacks, ...) is ever read as uninitialised stack garbage, and every field we
   * fold below (fx/fy/fw/fh/lct.size/lct.colors) is CONTENT, never an address. */
  gd_GIF gif;
  memset(&gif, 0, sizeof gif);
  enum { VB_GW = 200, VB_GH = 200 };
  gif.width  = VB_GW;
  gif.height = VB_GH;

  /* fx/fy are drawn IN-BOUNDS on purpose: read_image's own precondition
   * (fx<width && fy<height) must hold for the descriptor to actually be processed -- an
   * out-of-bounds draw would just take the trivial "return -1 immediately" edge every
   * time, which is a far weaker differential. */
  uint16_t _fx = (uint16_t)vb_len(VB_GW - 1);
  uint16_t _fy = (uint16_t)vb_len(VB_GH - 1);
  uint16_t _fw = (uint16_t)vb_take(2);
  uint16_t _fh = (uint16_t)vb_take(2);
  uint8_t  _fisrz = (uint8_t)vb_take(1);
  int _has_lct   = (_fisrz & 0x80) != 0;
  int _lct_size  = _has_lct ? (1 << ((_fisrz & 0x07) + 1)) : 0;  /* 2..256, mirrors read_image */
  int _lct_bytes = 3 * _lct_size;                                /* <= 768 == sizeof colors[] */

  /* Lay out the exact byte stream read_image expects to read from gif->fd, in its own
   * reading order: fx, fy, fw, fh (each a little-endian uint16, matching read_num()),
   * the flags byte, then -- iff the LCT flag is set -- the LCT color bytes, then a final
   * (deliberately invalid) LZW key-size byte. */
  unsigned char _filebuf[900];
  int _p = 0;
  _filebuf[_p++] = (unsigned char)(_fx & 0xFF);
  _filebuf[_p++] = (unsigned char)((_fx >> 8) & 0xFF);
  _filebuf[_p++] = (unsigned char)(_fy & 0xFF);
  _filebuf[_p++] = (unsigned char)((_fy >> 8) & 0xFF);
  _filebuf[_p++] = (unsigned char)(_fw & 0xFF);
  _filebuf[_p++] = (unsigned char)((_fw >> 8) & 0xFF);
  _filebuf[_p++] = (unsigned char)(_fh & 0xFF);
  _filebuf[_p++] = (unsigned char)((_fh >> 8) & 0xFF);
  _filebuf[_p++] = (unsigned char)_fisrz;
  for (int _k = 0; _k < _lct_bytes; _k++) _filebuf[_p++] = (unsigned char)vb_take(1);
  _filebuf[_p++] = 0x00;   /* invalid LZW key_size -> read_image_data returns -1 at once */

  char _tmpl[] = "/tmp/vb_gifdecXXXXXX";
  int _gfd = mkstemp(_tmpl);
  long vb_ret;
  if (_gfd >= 0) {
    unlink(_tmpl);
    write(_gfd, _filebuf, (size_t)_p);
    lseek(_gfd, 0, SEEK_SET);
    gif.fd = _gfd;
    vb_ret = (long)read_image(&gif);
    close(_gfd);
  } else {
    vb_ret = -999;   /* couldn't create the backing fd (should not happen) -- deterministic
                       * sentinel, gif is left all-zero so nothing else diverges either. */
  }

  vb_mix(&vb_ret, sizeof vb_ret);
  vb_mix(&gif.fx, sizeof gif.fx);
  vb_mix(&gif.fy, sizeof gif.fy);
  vb_mix(&gif.fw, sizeof gif.fw);
  vb_mix(&gif.fh, sizeof gif.fh);
  vb_mix(&gif.lct.size, sizeof gif.lct.size);
  { int _which = (gif.palette == &gif.lct) ? 1 : 0; vb_mix(&_which, sizeof _which); }
  /* Fold only the LCT prefix WE know we wrote (bounded <=768, the array's real capacity)
   * -- never a post-call, possibly-corrupted `gif.lct.size` -- so a miscompiled candidate
   * can never turn this fold itself into an out-of-bounds read. */
  if (_lct_bytes > 0) vb_mix(gif.lct.colors, (unsigned long)_lct_bytes);

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
