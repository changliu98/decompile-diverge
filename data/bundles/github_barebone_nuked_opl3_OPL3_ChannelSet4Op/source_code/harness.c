/* BYOH memstate harness for the github functional axis (recompile-pool promotion).
 *
 * TARGET SIGNATURE:
 *   static void OPL3_ChannelSet4Op(opl3_chip *chip, uint8_t data)
 *
 * WHY HAND-WRITTEN: `opl3_chip *chip` is a pointer to a large STRUCT (opl3.h) --
 * funcharness's automatic signature parser only knows int/float/char-string/T-array
 * params, so this is UnsupportedSignature for the generator.
 *
 * `opl3_chip` is NOT a POD-transparent struct like SCC/OPLL: opl3_channel and opl3_slot
 * hold internal pointers wired together at construction time (channel->slotz[0/1],
 * channel->pair, channel->chip, channel->out[0..3]; slot->channel, slot->chip, slot->mod,
 * slot->trem). OPL3_ChannelSet4Op's own call graph (OPL3_ChannelUpdateAlg ->
 * OPL3_ChannelSetupAlg) DEREFERENCES several of these (channel->chip->newm,
 * channel->pair->con / channel->pair->alg, channel->pair->slotz[0/1]->mod,
 * channel->slotz[0/1]->mod / ->out, ...) -- a zero-initialised struct would leave
 * `pair`/`slotz` NULL and SEGV the instant a 4-op bit is set. So we call the library's
 * OWN constructor, `OPL3_Reset()` (same TU, untouched by the splice -- only
 * OPL3_ChannelSet4Op's body is ever replaced), to wire up every channel's
 * chip/pair/slotz/out pointers exactly as a real chip does; that satisfies every
 * pointer-relationship precondition the target's call graph needs, with no NULL deref
 * possible for any (chip.newm, data) combination (verified against the call graph:
 * OPL3_Reset pairs channels {0,3} {1,4} {2,5} {9,12} {10,13} {11,14} symmetrically --
 * exactly the pairs OPL3_ChannelSet4Op computes via `chnum`/`chnum+3u` -- and every
 * channel it or its pair can reach already has valid slotz/chip/pair from Reset).
 *
 * OPL3_ChannelSet4Op(chip, data) picks, per bit 0..5 of `data`, one of those 6 "4-op
 * pairs" and sets the pair's `chtype` to ch_4op/ch_4op2 (bit set) or ch_2op/ch_2op (bit
 * clear), then recomputes `alg` via OPL3_ChannelUpdateAlg for the touched channels. We
 * drive `data` from the seed and `chip.newm` (the mode flag OPL3_ChannelUpdateAlg
 * branches on) from the seed too, call the target, then fold the CONTENT of every
 * channel's `chtype` and `alg` (both plain uint8_t scalars -- never a pointer) for all 18
 * channels into vb_digest. That captures the function's complete observable effect
 * (direct chtype writes + the alg it triggers downstream) while NEVER folding an
 * out[]/mod/pair/slotz/chip pointer -- those are addresses into the local `chip`
 * (stack-relative, NOT stable across independently-linked binaries) and folding them
 * would masquerade as a false vanish. A no-op (stub) body leaves every channel exactly as
 * OPL3_Reset left it (chtype=ch_2op, alg=0 for all 18) regardless of `data` -- so any
 * seed whose `data` byte is nonzero (~255/256 of them) diverges from that state under the
 * real function, discriminating identity from stub.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
