/* dump the program's writable globals (the deterministic part of the exit memstate). */
static void vb_dump(const char *path){
  VB_CUR=0; VB_N=0; VB_I=0;                  /* zero bookkeeping (VB_CUR holds a heap ptr) */
  if(!path) return;
  FILE *out = fopen(path, "wb"); if(!out) return;
  fwrite(__data_start, 1, (size_t)((char*)_edata   - (char*)__data_start), out);
  fwrite(__bss_start,  1, (size_t)((char*)_end     - (char*)__bss_start),  out);
  fclose(out); }

/* our own "virtual output stream" -- the pUserData an onSeek/onWrite callback PAIR can
 * legally operate on. Never a real file; purely in-memory bookkeeping so every write the
 * target performs always lands inside a buffer WE own. */
#define VB_WBUF 128
typedef struct {
  unsigned char buf[VB_WBUF];
  long pos;          /* current virtual position, always kept in [0, VB_WBUF) */
  int seekCount;     /* how many times onSeek was invoked */
  int writeCount;    /* how many times onWrite was invoked */
  int failSeekOn;    /* 0 = never fail; else fail (return DRWAV_FALSE) on this onSeek call number */
} vb_write_state;

static drwav_bool32 vb_onSeek(void *pUserData, int offset, drwav_seek_origin origin) {
  vb_write_state *st = (vb_write_state *)pUserData;
  st->seekCount += 1;
  if (st->failSeekOn != 0 && st->seekCount == st->failSeekOn) {
    return DRWAV_FALSE;
  }
  long newPos = (origin == DRWAV_SEEK_SET) ? (long)offset : (st->pos + (long)offset);
  if (newPos < 0) newPos = -newPos;
  st->pos = newPos % VB_WBUF;
  return DRWAV_TRUE;
}

static size_t vb_onWrite(void *pUserData, const void *pData, size_t bytesToWrite) {
  vb_write_state *st = (vb_write_state *)pUserData;
  st->writeCount += 1;
  long remaining = (long)VB_WBUF - st->pos;
  if (remaining < 0) remaining = 0;
  size_t avail = (size_t)remaining;
  size_t n = (bytesToWrite < avail) ? bytesToWrite : avail;
  if (n > 0) {
    memcpy(st->buf + st->pos, pData, n);
    st->pos += (long)n;
  }
  return bytesToWrite;   /* drwav_write_chunk_sizes ignores this return value */
}

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  vb_write_state vb_st;
  memset(&vb_st, 0, sizeof vb_st);
  {
    /* occasionally fail the 1st or 2nd onSeek call, to exercise the early-return paths too */
    int vb_failSel = vb_len(5); /* 0..5 */
    vb_st.failSeekOn = (vb_failSel == 1) ? 1 : (vb_failSel == 2) ? 2 : 0;
  }

  drwav vb_wav;
  memset(&vb_wav, 0, sizeof vb_wav);
  vb_wav.onSeek        = vb_onSeek;
  vb_wav.onWrite       = vb_onWrite;
  vb_wav.pUserData     = &vb_st;
  vb_wav.pMetadata     = NULL;
  vb_wav.metadataCount = 0;

  /* mostly exercise the real seek+write body (isSequentialWrite==0); occasionally hit the
   * early-return branch too, deterministically. */
  vb_wav.isSequentialWrite = (drwav_bool32)(vb_len(9) == 0);

  {
    int vb_c = vb_len(2); /* 0, 1 or 2 -- cycle through all three container kinds */
    vb_wav.container = (vb_c == 0) ? drwav_container_riff
                      : (vb_c == 1) ? drwav_container_w64
                                    : drwav_container_rf64;
  }

  /* small & non-negative so the target's internal (int) casts of these stay well-defined */
  vb_wav.dataChunkDataSize = (drwav_uint64)vb_take(2);   /* 0 .. 65535 */
  vb_wav.dataChunkDataPos  = (drwav_uint64)vb_take(2);   /* 0 .. 65535 */

  drwav_write_chunk_sizes(&vb_wav);

  /* fold the CONTENT of everything the callbacks observed: the bytes actually written into
   * the owned buffer, the final virtual position, and how many times each callback fired --
   * never vb_wav's or vb_st's own ADDRESS. */
  vb_mix(vb_st.buf, sizeof vb_st.buf);
  vb_mix(&vb_st.pos, sizeof vb_st.pos);
  vb_mix(&vb_st.seekCount, sizeof vb_st.seekCount);
  vb_mix(&vb_st.writeCount, sizeof vb_st.writeCount);

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
