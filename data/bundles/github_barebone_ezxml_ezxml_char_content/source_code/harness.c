  size_t len = 1 + (size_t)vb_len(VB_SCAP - 2);   /* range [1, VB_SCAP-1] */

  /* the tag's pre-existing `txt`: seed-chosen empty ("initial content" branch) vs a
   * fixed non-empty baseline ("append a copy" branch) -- ALWAYS a real malloc'd buffer
   * (built by hand -- no strdup dependency) so a realloc() on it (the EZXML_TXTM-set
   * branch) is never undefined behaviour regardless of which flag state is also drawn. */
