  if (vb_mode == 0) {
    vb_offsetFromStart = (drflac_uint64)vb_small;                              /* else-branch */
  } else if (vb_mode == 1) {
    vb_offsetFromStart = (drflac_uint64)0x7FFFFFFFULL + (drflac_uint64)vb_small;   /* if-branch, no while */
  } else {
    vb_offsetFromStart = (drflac_uint64)0x7FFFFFFFULL * 2ULL + (drflac_uint64)vb_small; /* if-branch + while x1 */
  }

  drflac_bool32 vb_ret = drflac__seek_to_byte(&vb_bs, vb_offsetFromStart);
  vb_mix(&vb_ret, sizeof vb_ret);

  /* fold the CONTENT of the mutated state: the virtual-stream position + how many times
   * (and how) the callback was actually invoked -- the observable effect of the call. */
  vb_mix(&vb_st.pos, sizeof vb_st.pos);
  vb_mix(&vb_st.callCount, sizeof vb_st.callCount);

  /* fold the CONTENT of bs's own bookkeeping fields the function mutates via
   * drflac__reset_cache() on success (left untouched -- i.e. still zero -- on failure). */
