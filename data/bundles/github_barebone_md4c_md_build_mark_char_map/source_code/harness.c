/* BYOH memstate harness for the github functional axis (recompile-pool promotion).
 *
 * TARGET SIGNATURE:
 *   static void md_build_mark_char_map(MD_CTX* ctx)
 *
 * WHY HAND-WRITTEN: `MD_CTX*` is a pointer to a large STRUCT -- funcharness's automatic
 * signature parser only knows int / float / char-string / T-array params, so this is
 * UnsupportedSignature for the generator. MD_CTX is fully transparent for this function's
 * purposes: md_build_mark_char_map only ever WRITES `ctx->mark_char_map[]` (a plain
 * `char[256]` -- MD4C_USE_UTF16 is not defined in this build, so the ASCII/UTF-8 256-byte
 * variant applies) and READS `ctx->parser.flags` (a plain `unsigned`). It never dereferences
 * any of MD_CTX's other pointer/callback members, so we can zero-init the whole struct
 * ourselves (no library constructor needed, no dangling-pointer precondition to satisfy)
 * and drive `parser.flags` directly from the seed.
 *
 * md_build_mark_char_map unconditionally memsets mark_char_map to 0, then unconditionally
 * marks 12 fixed characters, then conditionally marks up to 8 more characters (and possibly
 * the whole whitespace set) depending on individual MD_FLAG_* bits in ctx->parser.flags. We
 * draw flags as a raw 32-bit value from the seed so the corpus exercises every branch
 * (each flag bit independently ~50/50 across the seed set). We fold the CONTENT of the full
 * 256-byte output map (no pointers, no addresses) into vb_digest.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
