/* BYOH memstate harness for the github functional axis (recompile-pool promotion, cjson).
 *
 * TARGET SIGNATURE:
 *   CJSON_PUBLIC(void) cJSON_Delete(cJSON *item)
 *
 * WHY HAND-WRITTEN: `item` is a pointer to a linked/nested `cJSON` struct tree that in real
 * usage only comes from the cJSON_Parse or cJSON_Create family of constructors -- the auto
 * harness's signature parser only knows int/float/char-string/T-array params, never an
 * opaque struct pointer, so it cannot synthesise a call for this signature at all.
 *
 * cJSON_Delete is `void` and CONSUMES its argument (it frees every node it walks), so it
 * writes to no output buffer and there is nothing left to read back afterwards -- its ONLY
 * observable effect is which/how-many times the library's allocator hook
 * (`global_hooks.deallocate`, a plain file-scope function-pointer struct declared in cJSON.c,
 * visible here because `func.c` -- the whole TU -- is `#include`d above) gets invoked. We
 * install our OWN deallocate hook (a plain function pointer -- never a heap/stack ADDRESS we
 * read back) that increments a global counter and then performs the real `free()`, and fold
 * only that counter's CONTENT (never any freed pointer's value, never a struct field -- a
 * `cJSON` node embeds `next`/`prev`/`child`/`valuestring`/`string` POINTERS that would leak
 * heap addresses into the digest if read) into `vb_digest`.
 *
 * We build a small, fully self-owned tree (root object -> child string item -> sibling object
 * item -> its own child string item), never touching any cJSON constructor, so we know exactly
 * which allocations exist and which flags gate their freeing. About half the seeds mark the
 * inner object item's key (`->string`) `cJSON_StringIsConst` (a literal, never freed) instead
 * of a heap buffer, exercising cJSON_Delete's "don't free a const key" branch: a correct delete
 * makes 8 hook calls on that half and 9 on the other; a neutralised ("return;") body makes 0
 * either way -- that gap is the whole signal.
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
