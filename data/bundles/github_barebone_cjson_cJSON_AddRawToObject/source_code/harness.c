  char _name[11];
  for (int _k = 0; _k < _namelen; _k++) { _name[_k] = (char)('a' + (vb_take(1) % 26)); }
  _name[_namelen] = '\0';

  /* `raw`: the raw text payload cJSON_CreateRaw copies VERBATIM (no parsing) into
   * valuestring -- a seed-derived printable-ASCII string, 0..VB_STRLEN chars, always
   * NUL-terminated in-buffer and non-NULL. */
