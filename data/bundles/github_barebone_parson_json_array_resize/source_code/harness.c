  size_t _ar_count_after = _ar.count;
  vb_mix(&_ar_cap_after, sizeof _ar_cap_after);
  vb_mix(&_ar_count_after, sizeof _ar_count_after);

  /* content effect -- did every previously-stored number survive at its slot?
   * json_value_get_number is an UNCHANGED sibling getter; fold the returned NUMBER
   * CONTENT, never the JSON_Value* pointer itself. */
  for (size_t _i = 0; _i < _ar_count_after; _i++) {
    double _got = json_value_get_number(_ar.items[_i]);
    vb_mix_d(_got);
  }

