/* in-order walk of the surviving tree, folding (key, color, depth-from-root) for every
 * live node -- all CONTENT/shape signal, never a pointer/address. `sentinel` is the
 * table's own leaf marker (table->sentinel), not NULL. */
static void vb_walk(RBNode *n, RBNode *sentinel, int depth) {
  if (n == sentinel) return;
  vb_walk(n->left, sentinel, depth + 1);
  long key = (long)(intptr_t)n->key;
  unsigned char color = (unsigned char)n->color;
  long d = (long)depth;
  vb_mix(&key, sizeof key);
  vb_mix(&color, 1);
  vb_mix(&d, sizeof d);
  vb_walk(n->right, sentinel, depth + 1);
}

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* 12..32 distinct keys: enough tree depth/breadth that deleting half of them
   * (below) exercises every branch of rebalance_after_delete's while-loop -- RED
   * sibling rotation, BLACK sibling with BLACK children (recolor + move up), and
   * BLACK sibling with a RED child (recolor + rotate). */
  int n = 12 + vb_len(20);
  if (n > 40) n = 40;

  int order[40];
  for (int i = 0; i < n; i++) order[i] = i;
  for (int i = n - 1; i > 0; i--) {           /* Fisher-Yates -> INSERT order */
    int j = vb_len(i);
    int t = order[i]; order[i] = order[j]; order[j] = t;
  }

  CC_TreeTable *table = NULL;
  enum cc_stat st = cc_treetable_new(vb_tt_cmp, &table);

  if (st == CC_OK && table) {
    for (int i = 0; i < n; i++) {
      long k = order[i];
      cc_treetable_add(table, (void*)(intptr_t)k, (void*)(intptr_t)(k * 7 + 3));
    }

    int dorder[40];
    for (int i = 0; i < n; i++) dorder[i] = i;
    for (int i = n - 1; i > 0; i--) {         /* Fisher-Yates -> DELETE order */
      int j = vb_len(i);
      int t = dorder[i]; dorder[i] = dorder[j]; dorder[j] = t;
    }

    int ndel = n / 2;                          /* delete half, keep half to fold */
    for (int i = 0; i < ndel; i++) {
      long k = dorder[i];
      cc_treetable_remove(table, (void*)(intptr_t)k, NULL);
    }

    long sz = (long)table->size;               /* content scalar, safe to fold */
    vb_mix(&sz, sizeof sz);

    vb_walk(table->root, table->sentinel, 0);

    cc_treetable_destroy(table);
  }

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
