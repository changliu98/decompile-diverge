/* hand-built GumboOptions matching gumbo.h's documented defaults (kGumboDefaultOptions
 * itself is defined in parser.c, which we don't link -- tokenizer.c never calls into it). */
static void *vb_alloc(void *ud, size_t n){ (void)ud; return malloc(n); }
static void vb_dealloc(void *ud, void *p){ (void)ud; free(p); }
static const GumboOptions vb_options = {
  vb_alloc, vb_dealloc, NULL, 8, false, -1, GUMBO_TAG_LAST, GUMBO_NAMESPACE_HTML
};

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* Real GumboParser, built via the TU's own constructors -- never a hand-faked struct. */
  GumboParser _parser;
  memset(&_parser, 0, sizeof _parser);
  _parser._options = &vb_options;

  GumboOutput _out;
  memset(&_out, 0, sizeof _out);
  _parser._output = &_out;
  gumbo_init_errors(&_parser);                 /* TU's own helper (error.c) */

  /* fixed, well-formed input text for the utf8 iterator -- our exercised branches only
   * ever READ its current position/pointer (parse-error bookkeeping); none advance it. */
  static const char vb_text[] = "<a x>";
  gumbo_tokenizer_state_init(&_parser, vb_text, sizeof(vb_text) - 1);   /* TU's own ctor */
  gumbo_tokenizer_set_state(&_parser, GUMBO_LEX_BEFORE_ATTR_NAME);  /* the real state this handler runs under */
  initialize_tag_buffer(&_parser);             /* TU's own helper: (re)inits _tag_state._buffer,
                                                 * exactly as start_new_tag would have on tag open */

  GumboTokenizerState *_tok = _parser._tokenizer_state;
  GumboToken _tok_out;
  memset(&_tok_out, 0, sizeof _tok_out);

  /* `c` from one seed byte: 6/16 a regular attr-name char (default branch: state->ATTR_NAME
   * + tag-buffer append), 1/16 '/' (SELF_CLOSING_START_TAG, no buffer touch), 1/16 NUL
   * (parse error + state->ATTR_NAME + temporary-buffer append of U+FFFD), 4/16 a
   * quote/`<`/`=` char (parse error, then falls through to the same default effect),
   * 4/16 whitespace (NEXT_CHAR only, state unchanged -- a negative control). */
  unsigned char _b = (unsigned char)vb_take(1);
  int _c;
  switch (_b % 16) {
    case 0: _c = '\t'; break;
    case 1: _c = '\n'; break;
    case 2: _c = '\f'; break;
    case 3: _c = ' ';  break;
    case 4: _c = '/';  break;
    case 5: _c = 0;    break;
    case 6: _c = '"';  break;
    case 7: _c = '\''; break;
    case 8: _c = '<';  break;
    case 9: _c = '=';  break;
    default: _c = 'a' + (_b % 26); break;
  }

  long vb_ret = (long)handle_before_attr_name_state(&_parser, _tok, _c, &_tok_out);
  vb_mix(&vb_ret, sizeof vb_ret);

  long _state_after = (long)_tok->_state;
  vb_mix(&_state_after, sizeof _state_after);

  vb_mix(&_tok->_tag_state._buffer.length, sizeof _tok->_tag_state._buffer.length);
  vb_mix(_tok->_tag_state._buffer.data, _tok->_tag_state._buffer.length);

  vb_mix(&_tok->_temporary_buffer.length, sizeof _tok->_temporary_buffer.length);
  vb_mix(_tok->_temporary_buffer.data, _tok->_temporary_buffer.length);

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
