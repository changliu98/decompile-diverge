/* BYOH memstate harness for the github functional axis (recompile-pool promotion, msfgif_enc).
 *
 * TARGET SIGNATURE:
 *   static void msf_free_gif_state(MsfGifState * handle)
 *
 * WHY HAND-WRITTEN: `handle` is a pointer to an opaque `MsfGifState` struct that in real usage
 * is only ever populated by `msf_gif_begin()`/`msf_gif_frame()` -- the auto harness's signature
 * parser only knows int/float/char-string/T-array params, never a struct pointer, so it cannot
 * synthesise a call for this signature at all. We build the struct ourselves.
 *
 * msf_free_gif_state frees five pointer fields (`previousFrame.pixels`, `currentFrame.pixels`,
 * `lzwMem`, `tlbMem`, `usedMem`) via the library's `MSF_GIF_FREE` macro -- which, with no custom
 * allocator defined (case extra_cflags is just `-I. -DMSF_GIF_IMPL`), expands to plain `free()`
 * -- and walks+frees the `listHead` linked list of `MsfGifBuffer` nodes. Crucially it does NOT
 * null out the five pointer fields afterward (they become genuinely DANGLING), so we never read
 * them again post-call -- only `handle->listHead` is written back (unconditionally set to NULL
 * once the list is drained). That write lands in OUR local stack struct (through the pointer we
 * passed), so reading it back afterward is safe -- no use-after-free -- and it is CONTENT (a
 * null/non-null flag), never a heap/stack ADDRESS: we fold only the 0/1 boolean, never the
 * pointer value itself.
 *
 * We build handle from scratch (memset to zero, no library constructor call): five pointer
 * fields are seed-driven NULL-or-malloc'd (exercising each `if (handle->X)` guard), and a small
 * (0-3 node) `MsfGifBuffer` singly-linked list is heap-allocated with real, correctly-sized
 * `malloc(offsetof(MsfGifBuffer, data) + size)` blocks so the library's `free()` calls are valid.
 * A correct free empties a non-empty list back to `listHead == NULL`; a neutralised ("return;")
 * body leaves `listHead` exactly as we built it (non-NULL whenever list_len > 0) -- that gap,
 * folded as a boolean, is the whole signal. (ASAN leak detection is off project-wide
 * (`detect_leaks=0`, ddiv/functional.py), so a stub's un-freed allocations are silent by
 * design here -- the listHead-nulled boolean is the intended, deliberate oracle signal.)
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
