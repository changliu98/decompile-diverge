/* ---- synthetic JPEG byte-stream fed to picojpeg's need-bytes callback ---------------
 * Plain-CONTENT statics only (a byte buffer + an integer cursor) -- never an address --
 * so nothing here can leak into the memstate dump. */
#define VB_FAKE_LEN 24
static unsigned char vb_fake_buf[VB_FAKE_LEN];
static unsigned long vb_fake_pos;

static unsigned char vb_need_bytes(unsigned char *pBuf, unsigned char buf_size,
                                    unsigned char *pBytes_actually_read,
                                    void *pCallback_data)
{
  unsigned long remain = (vb_fake_pos < (unsigned long)VB_FAKE_LEN)
                         ? ((unsigned long)VB_FAKE_LEN - vb_fake_pos) : 0UL;
  unsigned long n = (remain < (unsigned long)buf_size) ? remain : (unsigned long)buf_size;
  (void)pCallback_data;
  if (n) { memcpy(pBuf, vb_fake_buf + vb_fake_pos, (size_t)n); vb_fake_pos += n; }
  *pBytes_actually_read = (unsigned char)n;
  return 0;   /* no callback error -- EOF is signalled by *pBytes_actually_read == 0, which
               * picojpeg's own getChar() turns into a deterministic synthetic 0xFF/0xD9
               * tail (see fillInBuf/getChar in func.c) -- never an OOB read of vb_fake_buf. */
}

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* locateSOFMarker(void): build a small synthetic "JPEG" stream so the call is
   * well-formed: FF D8 (SOI) then FF <marker> where <marker> is drawn from a small set
   * that exercises every branch of locateSOFMarker()'s own switch plus
   * processMarkers()'s early-return cases, then a run of raw seed bytes that becomes
   * readSOFMarker()'s header fields when the marker is M_SOF0 (length/precision/height/
   * width/component-count/component records) -- valid headers parse to a real
   * (width,height,...) state, malformed ones return one of picojpeg's PJPG_BAD_* codes;
   * either way the outcome is a deterministic function of the seed only. */
  {
    int _i;
    const unsigned char vb_markers[8] = {
      (unsigned char)M_SOF0, (unsigned char)M_SOF1, (unsigned char)M_SOF2,
      (unsigned char)M_SOF9, (unsigned char)M_DAC,  (unsigned char)M_RST0,
      (unsigned char)M_EOI,  (unsigned char)M_SOS
    };
    vb_fake_buf[0] = 0xFF; vb_fake_buf[1] = 0xD8;
    vb_fake_buf[2] = 0xFF;
    vb_fake_buf[3] = vb_markers[vb_take(1) % 8];
    for (_i = 4; _i < VB_FAKE_LEN; _i++)
      vb_fake_buf[_i] = (unsigned char)vb_take(1);
    vb_fake_pos = 0;

    g_pNeedBytesCallback = vb_need_bytes;
    g_pCallback_data = 0;
  }

  {
    uint8 vb_r = locateSOFMarker();
    long vb_ret = (long)vb_r;
    vb_mix(&vb_ret, sizeof vb_ret);
    /* fold the header fields readSOFMarker() may have populated -- CONTENT only (plain
     * uint8/uint16 values), never an address; already captured verbatim by the raw .bss
     * dump below too, folded here as an explicit, redundant signal (same rationale as
     * the sibling idctRows.c harness folding gCoeffBuf). */
    vb_mix(&gImageXSize, sizeof gImageXSize);
    vb_mix(&gImageYSize, sizeof gImageYSize);
    vb_mix(&gCompsInFrame, sizeof gCompsInFrame);
    vb_mix(gCompIdent, sizeof gCompIdent);
    vb_mix(gCompHSamp, sizeof gCompHSamp);
    vb_mix(gCompVSamp, sizeof gCompVSamp);
    vb_mix(gCompQuant, sizeof gCompQuant);

    /* Reset the picojpeg callback globals to the fixed neutral value 0 BEFORE the memstate
     * dump: g_pNeedBytesCallback held our own function's address only for the duration of
     * this call, and leaving it set would bake a load-time/relink-dependent code address
     * into the dumped .bss (see file header comment) -- an address leak, not a func0
     * signal, that would make the "same source -> same dump" identity check flaky. */
    g_pNeedBytesCallback = 0;
    g_pCallback_data = 0;
  }

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
