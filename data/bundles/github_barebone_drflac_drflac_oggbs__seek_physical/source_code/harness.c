/* our own call-tracking state -- the pUserData a real drflac_seek_proc callback can
 * legally dereference. Never a real file/socket; purely in-memory bookkeeping. */
typedef struct {
  int callCount;  /* how many times the callback was invoked */
  int failOn;     /* 0 = never fail; else fail (return DRFLAC_FALSE) on this call number */
} vb_seek_state;

static drflac_bool32 vb_on_seek(void *pUserData, int offset, drflac_seek_origin origin) {
  vb_seek_state *st = (vb_seek_state *)pUserData;
  (void)offset; (void)origin;
  st->callCount += 1;
  if (st->failOn != 0 && st->callCount == st->failOn) {
    return DRFLAC_FALSE;
  }
  return DRFLAC_TRUE;
}

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  vb_seek_state vb_st;
  memset(&vb_st, 0, sizeof vb_st);
  {
    /* occasionally make the Nth onSeek call fail, to exercise the early-return paths */
    int vb_failSel = vb_len(4); /* 0..4 */
    vb_st.failOn = (vb_failSel == 2) ? 1 : (vb_failSel == 3) ? 2 : (vb_failSel == 4) ? 3 : 0;
  }

  drflac_oggbs vb_oggbs;
  memset(&vb_oggbs, 0, sizeof vb_oggbs);
  vb_oggbs.onSeek = vb_on_seek;
  vb_oggbs.pUserData = &vb_st;
  /* baseline: the ONE field the function reads-then-writes (SEEK_CUR mode accumulates
   * into it); SEEK_SET mode overwrites it outright, so this only matters for CUR. */
  vb_oggbs.currentBytePos = (drflac_uint64)vb_take(4);

  /* offset magnitude: pick a band that deterministically exercises the direct branch,
   * the recurse-once-into-CUR branch, and the recurse-then-loop-once branch, each with a
   * HARD bound on iterations (never more than 2 loop turns) so it can never hang. */
  unsigned long vb_raw = vb_take(4);
  int vb_mode = vb_len(2);                                 /* 0, 1 or 2 */
  unsigned long vb_small = (vb_raw % 2000000UL) + 1UL;     /* 1 .. 2,000,000 */
  drflac_uint64 vb_offset;
  if (vb_mode == 0) {
    vb_offset = (drflac_uint64)vb_small;                                          /* <= 0x7FFFFFFF */
  } else if (vb_mode == 1) {
    vb_offset = (drflac_uint64)0x7FFFFFFFULL + (drflac_uint64)vb_small;           /* just over */
  } else {
    vb_offset = (drflac_uint64)0x7FFFFFFFULL * 2ULL + (drflac_uint64)vb_small;    /* needs the while-loop once */
  }
  int vb_sel = vb_len(1);   /* 0 or 1 */
  drflac_seek_origin vb_origin = (vb_sel == 0) ? DRFLAC_SEEK_SET : DRFLAC_SEEK_CUR;

  drflac_bool32 vb_ret = drflac_oggbs__seek_physical(&vb_oggbs, vb_offset, vb_origin);
  vb_mix(&vb_ret, sizeof vb_ret);

  /* fold the CONTENT of the observed effect: how many times the callback fired, and the
   * resulting physical-stream position bookkeeping -- never the pointers that carried it. */
  vb_mix(&vb_st.callCount, sizeof vb_st.callCount);
  drflac_uint64 vb_pos = vb_oggbs.currentBytePos;
  vb_mix(&vb_pos, sizeof vb_pos);

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
