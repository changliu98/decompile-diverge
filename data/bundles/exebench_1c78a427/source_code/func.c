#include <math.h>

void cquat_to_matrix_t(const double *q, double *m) {
# 206 "cquat_matrix.c"
 m[((1)-1)*(3)+((1)-1)] = 1.0-2.0*( q[2]*q[2] + q[1]*q[1] );
 m[((1)-1)*(3)+((2)-1)] = 2.0*( q[2]*q[3] + q[1]*q[0] );
 m[((1)-1)*(3)+((3)-1)] = 2.0*( q[2]*q[0] - q[1]*q[3] );

 m[((2)-1)*(3)+((1)-1)] = 2.0*( q[0]*q[1] - q[2]*q[3] );
 m[((2)-1)*(3)+((2)-1)] = 1.0-2.0*( q[0]*q[0] + q[2]*q[2] );
 m[((2)-1)*(3)+((3)-1)] = 2.0*( q[0]*q[3] + q[2]*q[1] );

 m[((3)-1)*(3)+((1)-1)] = 2.0*( q[1]*q[3] + q[0]*q[2] );
 m[((3)-1)*(3)+((2)-1)] = 2.0*( q[1]*q[2] - q[0]*q[3] );
 m[((3)-1)*(3)+((3)-1)] = 1.0-2.0*( q[1]*q[1] + q[0]*q[0] );
# 226 "cquat_matrix.c"
}
