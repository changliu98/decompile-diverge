/* dump the program's writable globals (the deterministic part of the exit memstate). */
static void vb_dump(const char *path){
  VB_CUR=0; VB_N=0; VB_I=0;                  /* zero bookkeeping (VB_CUR holds a heap ptr) */
  if(!path) return;
  FILE *out = fopen(path, "wb"); if(!out) return;
  fwrite(__data_start, 1, (size_t)((char*)_edata   - (char*)__data_start), out);
  fwrite(__bss_start,  1, (size_t)((char*)_end     - (char*)__bss_start),  out);
  fclose(out); }

int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* Precondition: bitarr must be a real BIT_ARRAY with words/num_of_bits/num_of_words/
   * capacity_in_words mutually consistent -- bit_array_alloc() (the library's own
   * constructor) guarantees that, starting empty (0 bits, capacity clamped to 8 words). */
  BIT_ARRAY arr;
  if (bit_array_alloc(&arr, 0) == NULL) {
    vb_dump(argc>2?argv[2]:NULL);
    return 0;
  }

  /* Synthesize a well-formed on-disk bit-array file from the seed: 8-byte header (number
   * of bits, native/little-endian host -> matches the format's on-disk LE convention)
   * followed by exactly roundup_bits2bytes(nbits) content bytes -- so both fread()s inside
   * bit_array_load ALWAYS succeed (the normal, in-contract path) instead of the short-read
   * early-return-0 branches, which would only be testing our own synthetic file's size. */
  int vb_nbits = vb_len(255);                         /* 0..255 bits -> 0..4 words */
  unsigned long vb_databytes = (unsigned long)((vb_nbits + 7) / 8);
  uint64_t vb_hdr = (uint64_t)vb_nbits;

  FILE *vb_fp = tmpfile();
  if (!vb_fp) {
    vb_dump(argc>2?argv[2]:NULL);
    return 0;
  }
  fwrite(&vb_hdr, 1, 8, vb_fp);
  {
    unsigned long _k;
    for (_k = 0; _k < vb_databytes; _k++) {
      unsigned char c = (unsigned char)vb_take(1);
      fwrite(&c, 1, 1, vb_fp);
    }
  }
  rewind(vb_fp);

  long vb_ret = (long)bit_array_load(&arr, vb_fp);
  fclose(vb_fp);
  vb_mix(&vb_ret, sizeof vb_ret);

  /* Fold the OUTCOME. `arr.words` is heap memory (invisible to the .data/.bss dump), so its
   * CONTENT -- never its address -- must be folded explicitly; num_of_bits/num_of_words are
   * re-read AFTER the call because a successful load resizes the array (a neutralised/stub
   * body leaves the freshly-allocated arr untouched -- still 0 bits / 0 words / zeroed --
   * which is exactly the observable difference this harness is built to catch). */
  {
    long vb_nbits_out = (long)arr.num_of_bits;
    long vb_nwords_out = (long)arr.num_of_words;
    vb_mix(&vb_nbits_out, sizeof vb_nbits_out);
    vb_mix(&vb_nwords_out, sizeof vb_nwords_out);
    if (arr.num_of_words > 0) {
      vb_mix(arr.words, sizeof(word_t) * (unsigned long)arr.num_of_words);
    }
  }

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
