/* BYOH memstate harness for github_bitarray_bit_array_load
 * (testable char bit_array_load(BIT_ARRAY* bitarr, FILE* f)).
 *
 * WHY funcharness.parse_signature can't drive this one: two reasons. (1) BIT_ARRAY is a
 * POINTER-RELATIONSHIP PRECONDITION struct (see the bit_array_mul_uint64 BYOH sibling in
 * this same directory for the full rationale) -- `words` must be a real heap buffer whose
 * size agrees with num_of_words/capacity_in_words. (2) the second parameter is a FILE*,
 * which the generator has no synthesis rule for at all.
 *
 * We solve both by (1) using the library's OWN constructor bit_array_alloc() to build a
 * valid, empty bitarr (capacity_in_words clamps to >=8 words = 64 bytes, comfortably
 * covering the <=255-bit / <=4-word load this harness exercises -- bit_array_load's own
 * internal bit_array_resize_critical() never needs to grow/realloc), and (2) synthesizing
 * a well-formed ON-DISK bit-array file with tmpfile() (a real, standard FILE* -- func.c's
 * own file-format comment: "[8 bytes num_of_bits][data, little-endian]"), sized so the
 * function ALWAYS takes its normal success path (never the short-read early-return-0
 * branches, which would just test our own file's sizing rather than the function itself).
 *
 * `bitarr.words` is heap memory (invisible to the .data/.bss memstate dump), so its
 * CONTENT -- never its address -- is folded into vb_digest explicitly after the call,
 * together with the (possibly grown) num_of_bits/num_of_words fields. */

