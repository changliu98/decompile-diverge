int main(int argc, char **argv){
  if(argc<2){ fprintf(stderr,"usage: %s <seed> [dump]\n", argv[0]); return 64; }
  FILE *fp=fopen(argv[1],"rb"); if(!fp){ perror("open"); return 64; }
  fseek(fp,0,SEEK_END); long fsz=ftell(fp); fseek(fp,0,SEEK_SET);
  unsigned char *buf=(unsigned char*)malloc(fsz>0?fsz:1);
  long nread=(long)fread(buf,1,fsz>0?fsz:0,fp); fclose(fp);
  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* bounded (1..20 byte), embedded-NUL-free string; mostly printable ASCII, ~1/8 of the
   * bytes forced to '\n' so the row/col-reset branch is exercised too. */
  int _len = 1 + vb_len(19);
  char _text[21];
  for (int _k = 0; _k < _len; ++_k) {
    unsigned char _b = (unsigned char)vb_take(1);
    _text[_k] = (_b % 8 == 0) ? '\n' : (char)(32 + (_b % 95));
  }
  _text[_len] = '\0';

  CSSLexer *_lex = init_css_lexer(_text);   /* TU's OWN unmodified constructor */

  /* call the target N times, N in [1, len+3] -- some seeds walk past `len` and hit the
   * "out of range" branch. */
  int _n = 1 + vb_len(_len + 2);
  for (int _k = 0; _k < _n; ++_k) {
    css_lexer_advance(_lex);                /* <-- function under test */
  }

  vb_mix(&_lex->i, sizeof _lex->i);
  vb_mix(&_lex->c, sizeof _lex->c);
  vb_mix(&_lex->row, sizeof _lex->row);
  vb_mix(&_lex->col, sizeof _lex->col);

  css_lexer_free(_lex);                     /* TU's OWN unmodified destructor */

  vb_dump(argc>2?argv[2]:NULL);
  return 0;
}
