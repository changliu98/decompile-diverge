  channel.ch_num = (uint8_t)vb_len(17);
  channel.alg    = (uint8_t)vb_take(1);

  OPL3_ChannelSetupAlg(&channel);

  /* Classify each of the 12 pointer fields OPL3_ChannelSetupAlg can write against the
   * fixed set of candidate targets it ever assigns from, folding only the resulting tag
   * (never the raw stack address -- see file banner) into vb_digest. */
#define VB_TAG(p) ( (p) == NULL ? -1 : \
                    (p) == &chip.zeromod  ? 0 : \
                    (p) == &slot0.fbmod   ? 1 : \
                    (p) == &slot0.out     ? 2 : \
                    (p) == &slot1.fbmod   ? 3 : \
                    (p) == &slot1.out     ? 4 : \
                    (p) == &pslot0.fbmod  ? 5 : \
                    (p) == &pslot0.out    ? 6 : \
                    (p) == &pslot1.fbmod  ? 7 : \
                    (p) == &pslot1.out    ? 8 : -2 )
