/* BYOH memstate harness for the github functional axis (recompile-pool promotion, stbwang).
 *
 * TARGET SIGNATURE:
 *   STBHW_EXTERN void stbhw_free_tileset(stbhw_tileset *ts)
 *
 * WHY HAND-WRITTEN: `ts` is a pointer to a `stbhw_tileset` struct that in real usage is only
 * ever populated by `stbhw_build_tileset_from_image()` -- the auto harness's signature parser
 * only knows int/float/char-string/T-array params, never a struct pointer, so it cannot
 * synthesise a call for this signature at all. We build the struct ourselves.
 *
 * stbhw_free_tileset frees each of the `num_h_tiles`/`num_v_tiles` heap blocks pointed to by
 * `h_tiles[]`/`v_tiles[]`, then the two pointer arrays themselves, then unconditionally writes
 * `h_tiles = v_tiles = NULL` and `num_h_tiles = max_h_tiles = num_v_tiles = max_v_tiles = 0`.
 * It never reads back anything it just freed. That final write lands in OUR local stack struct
 * (through the pointer we passed), so reading those six fields back afterward is safe -- no
 * use-after-free -- and every one is CONTENT (a null/non-null flag or a reset-to-0 counter),
 * never a heap/stack ADDRESS: we fold only 0/1 null-check booleans for the two pointers, and
 * the plain int counters, never a pointer value itself.
 *
 * We build ts from scratch (memset to zero, no library constructor call): num_h_tiles/
 * num_v_tiles (0..3) are seed-driven, max_h_tiles/max_v_tiles are >= the num_* counterpart (a
 * valid array-capacity invariant), the two pointer arrays are malloc'd to max-capacity, and
 * each of the first num_* slots holds a real `malloc(sizeof(stbhw_tile))` block so the
 * library's `free()` calls are always valid (freeing a slot past num_* never happens -- the
 * function only walks 0..num_h_tiles-1 / 0..num_v_tiles-1). A correct free empties both arrays
 * back to NULL/0; a neutralised ("return;") body leaves everything exactly as we built it
 * (non-NULL pointers whenever num_*>0, and the original nonzero counters) -- that gap, folded
 * as booleans + ints, is the whole signal. (ASAN leak detection is off project-wide
 * (`detect_leaks=0`, ddiv/functional.py), so a stub's un-freed allocations are silent by
 * design here -- the null/counter fields are the intended, deliberate oracle signal.)
 *
 * Structure = funcharness.PRELUDE + MAIN_OPEN + <middle> + HARNESS_FOOTER (verbatim).
 * Contract: the seed is already in the VB_CUR/VB_N byte cursor (MAIN_OPEN read argv[1]);
 * build the args from the seed, call the target, fold its return value + every output
 * buffer's CONTENT into vb_digest (vb_mix*), then vb_dump(argv[2]) & exit 0. */
/* auto-generated by ddiv.funcharness -- DO NOT EDIT */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
