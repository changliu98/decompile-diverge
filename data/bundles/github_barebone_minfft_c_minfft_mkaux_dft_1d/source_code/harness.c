  VB_CUR=buf; VB_N=nread; VB_I=0;

  /* N must be a positive power of two or the real function returns NULL by design; picking
   * N = 1<<p (p=0..10) means every seed is IN-CONTRACT and the genuine implementation always
   * succeeds, so a NULL return can only mean a neutralised/incorrect decompile. */
