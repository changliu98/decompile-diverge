    c[0] = a[0] * b[0] + a[1] * b[2];
    c[1] = a[0] * b[1] + a[1] * b[3];
    c[2] = a[2] * b[0] + a[3] * b[2];
    c[3] = a[2] * b[1] + a[3] * b[3];
    c[4] = a[4] * b[0] + a[5] * b[2];
    c[5] = a[4] * b[1] + a[5] * b[3];
    c[6] = a[6] * b[0] + a[7] * b[2];
    c[7] = a[6] * b[1] + a[7] * b[3];
