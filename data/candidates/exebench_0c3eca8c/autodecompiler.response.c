void expand(char s1[], char s2[]) {
 int i, j;
 if ((s1[0] >= '0' && s1[0] <= '9') && (s1[2] >= '0' && s1[2] <= '9')) {
  for (i = s1[0], j = 0; i <= s1[2]; ++i, ++j)
   s2[j] = i;
  s2[j] = '\0';
 }
 else if ((s1[0] >= 'A' && s1[0] <= 'Z') && (s1[2] >= 'A' && s1[2] <= 'Z')) {
  for (i = s1[0], j = 0; i <= s1[2]; ++i, ++j)
   s2[j] = i;
  s2[j] = '\0';
 }
 else if ((s1[0] >= 'a' && s1[0] <= 'z') && (s1[2] >= 'a' && s1[2] <= 'z')) {
  for (i = s1[0], j = 0; i <= s1[2]; ++i, ++j)
   s2[j] = i;
  s2[j] = '\0';
 }
}