void cquat_to_matrix_t(const double *q, double *m) {
  m[0] = 1.0 - 2.0 * (q[1] * q[1] + q[2] * q[2]);
  m[1] = 2.0 * (q[1] * q[2] + q[0] * q[3]);
  m[2] = 2.0 * (q[0] * q[2] - q[1] * q[3]);
  m[3] = 2.0 * (q[1] * q[3] - q[0] * q[2]);
  m[4] = 1.0 - 2.0 * (q[0] * q[0] + q[2] * q[2]);
  m[5] = 2.0 * (q[2] * q[1] + q[0] * q[3]);
  m[6] = 2.0 * (q[1] * q[2] + q[0] * q[2]);
  m[7] = 2.0 * (q[1] * q[3] - q[0] * q[1]);
  m[8] = 1.0 - 2.0 * (q[0] * q[0] + q[1] * q[1]);
}