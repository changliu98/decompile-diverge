void cquat_to_matrix_t(double A[3][3], double B[3][3]) {
    B[0][0] = -(A[1][1] * A[2][2] + A[1][2] * A[2][1]) * 2;
    B[0][1] = (A[0][1] * A[2][2] + A[0][2] * A[2][1]) * 2;
    B[0][2] = (A[0][1] * A[1][2] + A[0][2] * A[1][1]) * 2;
    B[1][0] = (A[1][0] * A[2][2] + A[1][2] * A[2][0]) * 2;
    B[1][1] = -(A[0][0] * A[2][2] + A[0][2] * A[2][0]) * 2;
    B[1][2] = (A[0][0] * A[1][2] + A[0][2] * A[1][0]) * 2;
    B[2][0] = (A[1][0] * A[2][1] + A[1][1] * A[2][0]) * 2;
    B[2][1] = (A[0][0] * A[2][1] + A[0][1] * A[2][0]) * 2;
    B[2][2] = -(A[0][0] * A[1][1] + A[0][1] * A[1][0]) * 2;
}