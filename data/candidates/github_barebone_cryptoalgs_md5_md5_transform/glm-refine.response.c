void __cdecl md5_transform(MD5_CTX *ctx, const uint8_t *data)
{
    uint32_t m[16];
    uint32_t a, b, c, d;

    // Load message block (little-endian)
    for (int i = 0; i < 16; i++) {
        m[i] = (uint32_t)data[i * 4] | 
               ((uint32_t)data[i * 4 + 1] << 8) | 
               ((uint32_t)data[i * 4 + 2] << 16) | 
               ((uint32_t)data[i * 4 + 3] << 24);
    }

    a = ctx->state[0];
    b = ctx->state[1];
    c = ctx->state[2];
    d = ctx->state[3];

    // Round 1: F(x, y, z) = (y & z) | (~y & x)  -- Note: mapped to (b & c) | (~b & d)
    a += m[ 0] + ((b & c) | (~b & d)) + 0xD76AA478; a = ((a >> 25) | (a << 7)) + b;
    d += m[ 1] + ((c & b) | (~c & a)) + 0xE8C7B756; d = ((d >> 20) | (d << 12)) + a;
    c += m[ 2] + ((b & a) | (~b & d)) + 0x242070DB; c = ((c >> 15) | (c << 17)) + d;
    b += m[ 3] + ((a & d) | (~a & c)) + 0xC1BDCEEE; b = ((b >> 10) | (b << 22)) + c;

    a += m[ 4] + ((b & c) | (~b & d)) + 0xF57C0FAF; a = ((a >> 25) | (a << 7)) + b;
    d += m[ 5] + ((c & b) | (~c & a)) + 0x4787C62A; d = ((d >> 20) | (d << 12)) + a;
    c += m[ 6] + ((b & a) | (~b & d)) + 0xA8304613; c = ((c >> 15) | (c << 17)) + d;
    b += m[ 7] + ((a & d) | (~a & c)) + 0xFD469501; b = ((b >> 10) | (b << 22)) + c;

    a += m[ 8] + ((b & c) | (~b & d)) + 0x698098D8; a = ((a >> 25) | (a << 7)) + b;
    d += m[ 9] + ((c & b) | (~c & a)) + 0x8B44F7AF; d = ((d >> 20) | (d << 12)) + a;
    c += m[10] + ((b & a) | (~b & d)) + 0xFFFF5BB1; c = ((c >> 15) | (c << 17)) + d;
    b += m[11] + ((a & d) | (~a & c)) + 0x895CD7BE; b = ((b >> 10) | (b << 22)) + c;

    a += m[12] + ((b & c) | (~b & d)) + 0x6B901122; a = ((a >> 25) | (a << 7)) + b;
    d += m[13] + ((c & b) | (~c & a)) + 0xFD987193; d = ((d >> 20) | (d << 12)) + a;
    c += m[14] + ((b & a) | (~b & d)) + 0xA679438E; c = ((c >> 15) | (c << 17)) + d;
    b += m[15] + ((a & d) | (~a & c)) + 0x49B40821; b = ((b >> 10) | (b << 22)) + c;

    // Round 2: G(x, y, z) = (z & x) | (~z & y) -- Note: mapped to (d & b) | (~d & c)
    a += m[ 1] + ((d & b) | (~d & c)) + 0xF61E2562; a = ((a >> 27) | (a << 5)) + b;
    d += m[ 6] + ((c & a) | (~c & b)) + 0xC040B340; d = ((d >> 23) | (d << 9)) + a;
    c += m[11] + ((b & d) | (~b & a)) + 0x265E5A51; c = ((c >> 18) | (c << 14)) + d;
    b += m[ 0] + ((a & c) | (~a & d)) + 0xE9B6C7AA; b = ((b >> 12) | (b << 20)) + c;

    a += m[ 5] + ((d & b) | (~d & c)) + 0xD62F105D; a = ((a >> 27) | (a << 5)) + b;
    d += m[10] + ((c & a) | (~c & b)) + 0x02441453; d = ((d >> 23) | (d << 9)) + a;
    c += m[15] + ((b & d) | (~b & a)) + 0xD8A1E681; c = ((c >> 18) | (c << 14)) + d;
    b += m[ 4] + ((a & c) | (~a & d)) + 0xE7D3FBC8; b = ((b >> 12) | (b << 20)) + c;

    a += m[ 9] + ((d & b) | (~d & c)) + 0x21E1CDE6; a = ((a >> 27) | (a << 5)) + b;
    d += m[14] + ((c & a) | (~c & b)) + 0xC33707D6; d = ((d >> 23) | (d << 9)) + a;
    c += m[ 3] + ((b & d) | (~b & a)) + 0xF4D50D87; c = ((c >> 18) | (c << 14)) + d;
    b += m[ 8] + ((a & c) | (~a & d)) + 0x455A14ED; b = ((b >> 12) | (b << 20)) + c;

    a += m[13] + ((d & b) | (~d & c)) + 0xA9E3E905; a = ((a >> 27) | (a << 5)) + b;
    d += m[ 2] + ((c & a) | (~c & b)) + 0xFCEFA3F8; d = ((d >> 23) | (d << 9)) + a;
    c += m[ 7] + ((b & d) | (~b & a)) + 0x676F02D9; c = ((c >> 18) | (c << 14)) + d;
    b += m[12] + ((a & c) | (~a & d)) + 0x8D2A4C8A; b = ((b >> 12) | (b << 20)) + c;

    // Round 3: H(x, y, z) = x ^ y ^ z
    a += m[ 5] + (d ^ c ^ b) + 0xFFFA3942; a = ((a >> 28) | (a << 4)) + b;
    d += m[ 8] + (c ^ b ^ a) + 0x8771F681; d = ((d >> 21) | (d << 11)) + a;
    c += m[11] + (b ^ a ^ d) + 0x6D9D6122; c = ((c >> 16) | (c << 16)) + d;
    b += m[14] + (a ^ d ^ c) + 0xFDE5380C; b = ((b >> 9)  | (b << 23)) + c;

    a += m[ 1] + (d ^ c ^ b) + 0xA4BEEA44; a = ((a >> 28) | (a << 4)) + b;
    d += m[ 4] + (c ^ b ^ a) + 0x4BDECFA9; d = ((d >> 21) | (d << 11)) + a;
    c += m[ 7] + (b ^ a ^ d) + 0xF6BB4B60; c = ((c >> 16) | (c << 16)) + d;
    b += m[10] + (a ^ d ^ c) + 0xBEBFBC70; b = ((b >> 9)  | (b << 23)) + c;

    a += m[13] + (d ^ c ^ b) + 0x289B7EC6; a = ((a >> 28) | (a << 4)) + b;
    d += m[ 0] + (c ^ b ^ a) + 0xEAA127FA; d = ((d >> 21) | (d << 11)) + a;
    c += m[ 3] + (b ^ a ^ d) + 0xD4EF3085; c = ((c >> 16) | (c << 16)) + d;
    b += m[ 6] + (a ^ d ^ c) + 0x04881D05; b = ((b >> 9)  | (b << 23)) + c;

    a += m[ 9] + (d ^ c ^ b) + 0xD9D4D039; a = ((a >> 28) | (a << 4)) + b;
    d += m[12] + (c ^ b ^ a) + 0xE6DB99E5; d = ((d >> 21) | (d << 11)) + a;
    c += m[15] + (b ^ a ^ d) + 0x1FA27CF8; c = ((c >> 16) | (c << 16)) + d;
    b += m[ 2] + (a ^ d ^ c) + 0xC4AC5665; b = ((b >> 9)  | (b << 23)) + c;

    // Round 4: I(x, y, z) = c ^ (b | ~d) -- Note: mapped to c ^ (b | ~d)
    a += m[ 0] + (c ^ (b | ~d)) + 0xF4292244; a = ((a >> 26) | (a << 6)) + b;
    d += m[ 7] + (b ^ (a | ~c)) + 0x432AFF97; d = ((d >> 22) | (d << 10)) + a;
    c += m[14] + (a ^ (d | ~b)) + 0xAB9423A7; c = ((c >> 17) | (c << 15)) + d;
    b += m[ 5] + (d ^ (c | ~a)) + 0xFC93A039; b = ((b >> 11) | (b << 21)) + c;

    a += m[12] + (c ^ (b | ~d)) + 0x655B59C3; a = ((a >> 26) | (a << 6)) + b;
    d += m[ 3] + (b ^ (a | ~c)) + 0x8F0CCC92; d = ((d >> 22) | (d << 10)) + a;
    c += m[10] + (a ^ (d | ~b)) + 0xFFEFF47D; c = ((c >> 17) | (c << 15)) + d;
    b += m[ 1] + (d ^ (c | ~a)) + 0x85845DD1; b = ((b >> 11) | (b << 21)) + c;

    a += m[ 8] + (c ^ (b | ~d)) + 0x6FA87E4F; a = ((a >> 26) | (a << 6)) + b;
    d += m[15] + (b ^ (a | ~c)) + 0xFE2CE6E0; d = ((d >> 22) | (d << 10)) + a;
    c += m[ 6] + (a ^ (d | ~b)) + 0xA3014314; c = ((c >> 17) | (c << 15)) + d;
    b += m[13] + (d ^ (c | ~a)) + 0x4E0811A1; b = ((b >> 11) | (b << 21)) + c;

    a += m[ 4] + (c ^ (b | ~d)) + 0xF7537E82; a = ((a >> 26) | (a << 6)) + b;
    d += m[11] + (b ^ (a | ~c)) + 0xBD3AF235; d = ((d >> 22) | (d << 10)) + a;
    c += m[ 2] + (a ^ (d | ~b)) + 0x2AD7D2BB; c = ((c >> 17) | (c << 15)) + d;
    b += m[ 9] + (d ^ (c | ~a)) + 0xEB86D391; b = ((b >> 11) | (b << 21)) + c;

    ctx->state[0] += a;
    ctx->state[1] += b;
    ctx->state[2] += c;
    ctx->state[3] += d;
}