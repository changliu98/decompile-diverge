void lin_solve_3(double x[3], double A[3][3], double y[3])
{
    double det = A[0][0]*(A[1][1]*A[2][2] - A[1][2]*A[2][1]) +
                 A[0][1]*(A[1][2]*A[2][0] - A[1][0]*A[2][2]) +
                 A[0][2]*(A[1][0]*A[2][1] - A[1][1]*A[2][0]);

    double idet = 1.0 / det;

    x[0] = idet*(A[1][1]*A[2][2] - A[1][2]*A[2][1])*y[0] +
           idet*(A[1][2]*A[2][0] - A[1][0]*A[2][2])*y[1] +
           idet*(A[1][0]*A[2][1] - A[1][1]*A[2][0])*y[2];

    x[1] = idet*(A[0][2]*A[2][1] - A[0][1]*A[2][2])*y[0] +
           idet*(A[0][0]*A[2][2] - A[0][2]*A[2][0])*y[1] +
           idet*(A[0][1]*A[2][0] - A[0][0]*A[2][1])*y[2];

    x[2] = idet*(A[0][1]*A[1][2] - A[0][2]*A[1][1])*y[0] +
           idet*(A[0][2]*A[1][0] - A[0][0]*A[1][2])*y[1] +
           idet*(A[0][0]*A[1][1] - A[0][1]*A[1][0])*y[2];
}