void getTransf(double *p, double *A, double *B) {
  B[0] = p[2];
  B[1] = p[3];
  B[2] = 0.0;
  B[3] = 0.0;
  B[4] = p[4];
  B[5] = 0.0;
  B[6] = p[0];
  B[7] = p[1];
  B[8] = 1.0;
  A[0] = 1.0 / p[7];
  A[1] = -p[8] / p[7] / p[9];
  A[2] = 0.0;
  A[3] = 0.0;
  A[4] = 1.0 / p[9];
  A[5] = 0.0;
  A[6] = -p[5] / p[7];
  A[7] = (p[5] * p[8] - p[6] * p[7]) / p[7] / p[9];
  A[8] = 1.0;
}