void ne_post_filter8_double(double *x, const double *y, const int *f)
{
    double t[8];
    t[7] = y[0] - y[7];
    t[6] = y[1] - y[6];
    t[5] = y[2] - y[5];
    t[4] = y[3] - y[4];
    t[3] = t[4] / 2.0;
    t[2] = t[5] / 2.0;
    t[1] = t[6] / 2.0;
    t[0] = t[7] / 2.0;
    t[4] -= t[5] * f[7] / 6.0;
    t[5] -= t[4] * f[4] / 6.0;
    t[5] -= t[6] * f[8] / 6.0;
    t[6] -= t[5] * f[5] / 6.0;
    t[6] -= t[7] * f[9] / 6.0;
    t[7] -= t[6] * f[6] / 6.0;
    t[7] *= 6.0;
    t[7] /= f[3];
    t[6] *= 6.0;
    t[6] /= f[2];
    t[5] *= 6.0;
    t[5] /= f[1];
    t[4] *= 6.0;
    t[4] /= f[0];
    x[0] = y[0] - t[0] + t[7] / 2.0;
    x[1] = y[1] - t[1] + t[6] / 2.0;
    x[2] = y[2] - t[2] + t[5] / 2.0;
    x[3] = y[3] - t[3] + t[4] / 2.0;
    x[4] = x[3] - t[4];
    x[5] = x[2] - t[5];
    x[6] = x[1] - t[6];
    x[7] = x[0] - t[7];
}