double lagrange4(double *x, float *y, double x0) {
  double y0;
  y0 = y[0] * (x0 - x[1]) * (x0 - x[2]) * (x0 - x[3]) /
           ((x[0] - x[1]) * (x[0] - x[2]) * (x[0] - x[3])) +
       y[1] * (x0 - x[0]) * (x0 - x[2]) * (x0 - x[3]) /
           ((x[1] - x[0]) * (x[1] - x[2]) * (x[1] - x[3])) +
       y[2] * (x0 - x[0]) * (x0 - x[1]) * (x0 - x[3]) /
           ((x[2] - x[0]) * (x[2] - x[1]) * (x[2] - x[3])) +
       y[3] * (x0 - x[0]) * (x0 - x[1]) * (x0 - x[2]) /
           ((x[3] - x[0]) * (x[3] - x[1]) * (x[3] - x[2]));
  return y0;
}