void add_ang_mom(double *L, float *r, float *p) {
    // L[0] += (r[1] - p[1]) * (r[2] - p[2])
    L[0] += (double)((r[1] - p[1]) * (r[2] - p[2]));
    
    // L[0] -= (r[2] - p[2]) * (r[1] - p[1])
    L[0] -= (double)((r[2] - p[2]) * (r[1] - p[1]));
    
    // L[1] += (r[2] - p[2]) * (r[0] - p[0])
    L[1] += (double)((r[2] - p[2]) * (r[0] - p[0]));
    
    // L[1] -= (r[0] - p[0]) * (r[2] - p[2])
    L[1] -= (double)((r[0] - p[0]) * (r[2] - p[2]));
    
    // L[2] += (r[0] - p[0]) * (r[1] - p[1])
    L[2] += (double)((r[0] - p[0]) * (r[1] - p[1]));
    
    // L[2] -= (r[1] - p[1]) * (r[0] - p[0])
    L[2] -= (double)((r[1] - p[1]) * (r[0] - p[0]));
}