void arx_bwd(unsigned char *x) {
  x[2] = (x[2] << 4) | (x[2] >> 4);
  x[1] ^= x[2];
  x[3] ^= x[0];
  x[1] = (x[1] << 5) | (x[1] >> 3);
  x[3] = (x[3] << 1) | (x[3] >> 7);
  x[0] -= x[3];
  x[2] -= x[1];
  x[0] = (x[0] << 4) | (x[0] >> 4);
  x[1] ^= x[0];
  x[3] ^= x[2];
  x[1] = (x[1] << 6) | (x[1] >> 2);
  x[3] = (x[3] << 3) | (x[3] >> 5);
  x[0] -= x[1];
  x[2] -= x[3];
}