void vc1_inv_trans_8x8_c(int16_t *block)
{
    int i, j;
    int t1, t2, t3, t4, t5, t6, t7, t8;
    int tmp[64];
    int16_t *bp;

    bp = block;
    for (i = 0; i < 8; i++) {
        t1 = bp[0] + bp[32];
        t2 = bp[0] - bp[32];
        t3 = (bp[16] << 4) + (bp[48] << 1);
        t4 = (bp[16] << 1) - (bp[48] << 4);
        t5 = t1 + t3;
        t6 = t2 + t4;
        t7 = t2 - t4;
        t8 = t1 - t3;
        t1 = bp[8] + (bp[24] << 3) + (bp[40] << 2) + (bp[56] << 1);
        t2 = (bp[8] << 3) - (bp[24] << 1) - (bp[40] << 4) - (bp[56] << 2);
        t3 = (bp[8] << 2) - (bp[24] << 4) + (bp[40] << 1) + (bp[56] << 3);
        t4 = (bp[8] << 1) - (bp[24] << 2) + (bp[40] << 3) - (bp[56] << 4);
        tmp[0] = (t5 + t1) >> 3;
        tmp[1] = (t6 + t2) >> 3;
        tmp[2] = (t7 + t3) >> 3;
        tmp[3] = (t8 + t4) >> 3;
        tmp[4] = (t8 - t4) >> 3;
        tmp[5] = (t7 - t3) >> 3;
        tmp[6] = (t6 - t2) >> 3;
        tmp[7] = (t5 - t1) >> 3;
        bp++;
        tmp += 8;
    }

    bp = block;
    tmp = block;
    for (i = 0; i < 8; i++) {
        t1 = bp[0] + bp[32];
        t2 = bp[0] - bp[32];
        t3 = (bp[16] << 4) + (bp[48] << 1);
        t4 = (bp[16] << 1) - (bp[48] << 4);
        t5 = t1 + t3;
        t6 = t2 + t4;
        t7 = t2 - t4;
        t8 = t1 - t3;
        t1 = bp[8] + (bp[24] << 3) + (bp[40] << 2) + (bp[56] << 1);
        t2 = (bp[8] << 3) - (bp[24] << 1) - (bp[40] << 4) - (bp[56] << 2);
        t3 = (bp[8] << 2) - (bp[24] << 4) + (bp[40] << 1) + (bp[56] << 3);
        t4 = (bp[8] << 1) - (bp[24] << 2) + (bp[40] << 3) - (bp[56] << 4);
        tmp[0] = (t5 + t1 + 0x40) >> 7;
        tmp[8] = (t6 + t2 + 0x40) >> 7;
        tmp[16] = (t7 + t3 + 0x40) >> 7;
        tmp[24] = (t8 + t4 + 0x40) >> 7;
        tmp[32] = (t8 - t4 + 0x40) >> 7;
        tmp[40] = (t7 - t3 + 0x40) >> 7;
        tmp[48] = (t6 - t2 + 0x40) >> 7;
        tmp[56] = (t5 - t1 + 0x40) >> 7;
        bp++;
        tmp++;
    }
}