void ne_pre_filter8_double(double *y, double *x, int *f)
{







  double t[8];
  t[0] = (x[0] - x[7]) * f[3] / 32768.0;
  t[1] = (x[1] - x[6]) * f[2] / 32768.0;
  t[2] = (x[2] - x[5]) * f[1] / 32768.0;
  t[3] = (x[3] - x[4]) * f[0] / 32768.0;
  t[4] = (t[3] * f[4] / 32768.0 + t[2]) * f[5] / 32768.0 + t[1];
  t[5] = (t[4] * f[8] / 32768.0 + t[3]) * f[7] / 32768.0 + t[0];
  t[6] = (t[5] * f[9] / 32768.0 + t[4]) * f[6] / 32768.0 + t[1];
  t[7] = (t[6] * f[9] / 32768.0 + t[5]) * f[8] / 32768.0 + t[2];
  y[0] = x[0] - (x[0] - x[7]) / 2.0 + t[6] / 2.0;
  y[1] = x[1] - (x[1] - x[6]) / 2.0 + t[7] / 2.0;
  y[2] = x[2] - (x[2] - x[5]) / 2.0 + t[0] / 2.0;
  y[3] = x[3] - (x[3] - x[4]) / 2.0 + t[1] / 2.0;
  y[4] = y[3] - t[1];
  y[5] = y[2] - t[0];
  y[6] = y[1] - t[7];
  y[7] = y[0] - t[6];
}