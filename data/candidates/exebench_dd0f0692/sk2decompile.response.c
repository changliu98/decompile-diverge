           a[3] * a[6] * a[12] - a[2] * a[4] * a[15] - a[0] * a[7] * a[14];
  tmp[13] = a[0] * a[6] * a[11] + a[2] * a[7] * a[8] + a[3] * a[4] * a[10] -
            a[3] * a[6] * a[8] - a[2] * a[4] * a[11] - a[0] * a[7] * a[10];
