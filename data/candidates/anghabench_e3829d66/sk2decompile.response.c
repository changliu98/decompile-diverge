double blue_filter(double x, double *y) {
  double b;
  y[0] = 0.0555179 * x - 0.99886 * y[0];
  y[1] = 0.0750759 * x - 0.99332 * y[1];
  y[2] = 0.153852 * x - 0.969 * y[2];
  y[3] = 0.3104856 * x - 0.8665 * y[3];
  y[4] = 0.5329522 * x - 0.55 * y[4];
  y[5] = -0.016898 * x + 0.7616 * y[5];
  b = x * 0.5362 + y[0] + y[1] + y[2] + y[3] + y[4] + y[5] + y[6];
  y[6] = 0.115926 * x;
  return 0.11 * b;
}