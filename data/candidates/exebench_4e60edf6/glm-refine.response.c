void __cdecl warp_mat4_fill_transpose(float *out, const float *in)
{
    float (*m)[4] = (float (*)[4])in;
    float (*t)[4] = (float (*)[4])out;

    t[0][0] = m[0][0];
    t[0][1] = m[1][0];
    t[0][2] = m[2][0];
    t[0][3] = m[3][0];

    t[1][0] = m[0][1];
    t[1][1] = m[1][1];
    t[1][2] = m[2][1];
    t[1][3] = m[3][1];

    t[2][0] = m[0][2];
    t[2][1] = m[1][2];
    t[2][2] = m[2][2];
    t[2][3] = m[3][2];

    t[3][0] = m[0][3];
    t[3][1] = m[1][3];
    t[3][2] = m[2][3];
    t[3][3] = m[3][3];
}