void ne_post_filter16_double(double *out, const double *in, const int *coeff) {
  double a0 = in[0] - in[15];
  double a1 = in[1] - in[14];
  double a2 = in[2] - in[13];
  double a3 = in[3] - in[12];
  double a4 = in[4] - in[11];
  double a5 = in[5] - in[10];
  double a6 = in[6] - in[9];
  double a7 = in[7] - in[8];
  double a8 = in[7] - a7 / 2;
  double a9 = in[6] - a6 / 2;
  double a10 = in[5] - a5 / 2;
  double a11 = in[4] - a4 / 2;
  double a12 = in[3] - a3 / 2;
  double a13 = in[2] - a2 / 2;
  double a14 = in[1] - a1 / 2;
  double a15 = in[0] - a0 / 2;
  a7 -= a6 * coeff[15] / 16;
  a6 -= a7 * coeff[8] / 16;
  a6 -= a5 * coeff[16] / 16;
  a5 -= a6 * coeff[9] / 16;
  a5 -= a4 * coeff[17] / 16;
  a4 -= a5 * coeff[10] / 16;
  a4 -= a3 * coeff[18] / 16;
  a3 -= a4 * coeff[11] / 16;
  a3 -= a2 * coeff[19] / 16;
  a2 -= a3 * coeff[12] / 16;
  a2 -= a1 * coeff[20] / 16;
  a1 -= a2 * coeff[13] / 16;
  a1 -= a0 * coeff[21] / 16;
  a0 = 16 * (a0 - a1 * coeff[14] / 16) / coeff[7];
  a1 = 16 * a1 / coeff[6];
  a2 = 16 * a2 / coeff[5];
  a3 = 16 * a3 / coeff[4];
  a4 = 16 * a4 / coeff[3];
  a5 = 16 * a5 / coeff[2];
  a6 = 16 * a6 / coeff[1];
  a7 = 16 * a7 / coeff[0];
  a15 += a0 / 2;
  a14 += a1 / 2;
  a13 += a2 / 2;
  a12 += a3 / 2;
  a11 += a4 / 2;
  a10 += a5 / 2;
  a9 += a6 / 2;
  a8 += a7 / 2;
  out[0] = a15;
  out[1] = a14;
  out[2] = a13;
  out[3] = a12;
  out[4] = a11;
  out[5] = a10;
  out[6] = a9;
  out[7] = a8;
  out[8] = a8 - a7;
  out[9] = a9 - a6;
  out[10] = a10 - a5;
  out[11] = a11 - a4;
  out[12] = a12 - a3;
  out[13] = a13 - a2;
  out[14] = a14 - a1;
  out[15] = a15 - a0;
}