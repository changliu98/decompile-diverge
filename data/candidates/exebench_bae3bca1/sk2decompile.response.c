void bn_sqr_comba8(unsigned long *d, unsigned long *a) {
  unsigned long a00, a01, a02, a03, a04, a05, a06, a07;
  a00 = a[0] * a[0];
  a01 = a[0] * a[1];
  a02 = a[0] * a[2];
  a03 = a[0] * a[3];
  a04 = a[0] * a[4];
  a05 = a[0] * a[5];
  a06 = a[0] * a[6];
  a07 = a[0] * a[7];
  d[0] = a00;
  d[1] = a01 + (a00 << 1);
  d[2] = a02 + (a01 << 1) + (a00 << 1);
  d[3] = a03 + (a02 << 1) + (a01 << 1) + (a00 << 1);
  d[4] = a04 + (a03 << 1) + (a02 << 1) + (a01 << 1) + (a00 << 1);
  d[5] = a05 + (a04 << 1) + (a03 << 1) + (a02 << 1) + (a01 << 1) + (a00 << 1);
  d[6] = a06 + (a05 << 1) + (a04 << 1) + (a03 << 1) + (a02 << 1) + (a01 << 1) +
         (a00 << 1);
  d[7] = a07 + (a06 << 1) + (a05 << 1) + (a04 << 1) + (a03 << 1) + (a02 << 1) +
         (a01 << 1) + (a00 << 1);
}