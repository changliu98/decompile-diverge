void Mat4_RotateQuaternion(float *dst, float *q) {
  float qx = -q[0];
  float qy = -q[1];
  float qz = -q[2];
  float qw = q[3];
  float m00 = dst[0];
  float m01 = dst[1];
  float m02 = dst[2];
  float m03 = dst[3];
  float m10 = dst[4];
  float m11 = dst[5];
  float m12 = dst[6];
  float m13 = dst[7];
  float m20 = dst[8];
  float m21 = dst[9];
  float m22 = dst[10];
  float m23 = dst[11];
  float m30 = dst[12];
  float m31 = dst[13];
  float m32 = dst[14];
  float m33 = dst[15];
  dst[0] = m00 + qw * q[0] + qz * m01 + qy * m02;
  dst[1] = m01 + qw * q[1] + qz * m00 + qx * m02;
  dst[2] = m02 + qw * q[2] + qy * m00 + qx * m01;
  dst[3] = m03 + qw * q[3] - qx * m00 - qy * m01 - qz * m02;
  dst[3] = 0.0f;
  dst[4] = m10 + qw * q[0] + qy * m03 + qz * m11;
  dst[5] = m11 + qw * q[1] + qz * m03 + qx * m11;
  dst[6] = m12 + qw * q[2] + qx * m03 + qy * m11;
  dst[7] = m13 + qw * q[3] - qx * m03 - qz * m11 - qy * m12;
  dst[7] = 0.0f;
  dst[8] = m20 + qw * q[0] + qz * m10 + qy * m13;
  dst[9] = m21 + qw * q[1] + qy * m10 + qx * m13;
  dst[10] = m22 + qw * q[2] + qx * m10 + qz * m13;
  dst[11] = m23 + qw * q[3] - qx * m10 - qy * m13 - qz * m12;
  dst[11] = 0.0f;
  dst[12] = m30;
  dst[13] = m31;
  dst[14] = m32;
  dst[15] = m33;
}