void swapdouble(double *d)
{
  int i = ( ( d[0] & 0xff000000 ) >> 24 ) | ( ( d[0] & 0x00ff0000 ) >> 8 ) | ( ( d[0] & 0x0000ff00 ) << 8 ) | ( ( d[0] & 0x000000ff ) << 24 );
  int j = ( ( d[1] & 0xff000000 ) >> 24 ) | ( ( d[1] & 0x00ff0000 ) >> 8 ) | ( ( d[1] & 0x0000ff00 ) << 8 ) | ( ( d[1] & 0x000000ff ) << 24 );
  d[0] = i;
  d[1] = j;
}