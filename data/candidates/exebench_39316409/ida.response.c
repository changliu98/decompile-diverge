  c[6] = a[14] * b[7] + a[10] * b[6] + a[2] * b[4] + a[6] * b[5];
  c[7] = a[15] * b[7] + a[11] * b[6] + a[3] * b[4] + a[7] * b[5];
  c[8] = a[12] * b[11] + a[8] * b[10] + *a * b[8] + a[4] * b[9];
  c[9] = a[13] * b[11] + a[9] * b[10] + a[1] * b[8] + a[5] * b[9];
  c[10] = a[14] * b[11] + a[10] * b[10] + a[2] * b[8] + a[6] * b[9];
  c[11] = a[15] * b[11] + a[11] * b[10] + a[3] * b[8] + a[7] * b[9];
