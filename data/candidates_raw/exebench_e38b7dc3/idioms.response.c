void iop_iter(float *ioptr)
{
  float f0r; float f0i;
  float f1r; float f1i;
  float f2r; float f2i;
  float f3r; float f3i;
  float t0r; float t0i;
  float t1r; float t1i;
  float f1ra; float f1ia;
  float f2ra; float f2ia;
  float f2rb; float f2ib;
  float f3ra; float f3ia;
  float f1rb; float f1ib;
  float f1rc; float f1ic;
  float f0ia; float f0ib;
  float t0ra; float t0ia;
  float t1ra; float t1ia;
  f0r = ioptr[0];
  f0i = ioptr[1];
  f1r = ioptr[4];
  f1i = ioptr[5];
  f2r = ioptr[2];
  f2i = ioptr[3];
  f3r = ioptr[6];
  f3i = ioptr[7];
  t0r = f0r + f1r;
  t0i = f0i + f1i;
  f1ra = f0r - f1r;
  f1ia = f0i - f1i;
  t1r = f2r - f3r;
  t1i = f2i - f3i;
  f2ra = f2r + f3r;
  f2ia = f2i + f3i;
  f0r = t0r + f2ra;
  f0i = t0i + f2ia;
  f2rb = t0r - f2ra;
  f2ib = t0i - f2ia;
  f3ra = f1ra - t1i;
  f3ia = f1ia + t1r;
  f1rb = f1ra + t1i;
  f1ib = f1ia - t1r;
  t0ra = f0r + f0i;
  t0ia = f0r - f0i;
  t1ra = f1rb + f3ra;
  t1ia = f1ib - f3ia;
  f0ia = t1ra - f1rb;
  f1rc = t1ra + t1ra - f0ia;
  f1ic = t1ra - t1ra - f0ia;
  ioptr[4] = f2rb;
  ioptr[5] = f2ib;
  ioptr[0] = t0ra;
  ioptr[1] = t0ia;
  ioptr[2] = f1rc * .5f;
  ioptr[3] = f1ic * .5f;
  ioptr[6] = (t1ra * 2 + f1rc) * .5f;
  ioptr[7] = (t1ra * 2 - f1ic) * .5f;
}