void dmat_mul(double *out, double *left, double *right)
{
  double l00 = left[0 * 4 + 0];
  double l01 = left[0 * 4 + 1];
  double l02 = left[0 * 4 + 2];
  double l03 = left[0 * 4 + 3];
  double l10 = left[1 * 4 + 0];
  double l11 = left[1 * 4 + 1];
  double l12 = left[1 * 4 + 2];
  double l13 = left[1 * 4 + 3];
  double l20 = left[2 * 4 + 0];
  double l21 = left[2 * 4 + 1];
  double l22 = left[2 * 4 + 2];
  double l23 = left[2 * 4 + 3];
  double l30 = left[3 * 4 + 0];
  double l31 = left[3 * 4 + 1];
  double l32 = left[3 * 4 + 2];
  double l33 = left[3 * 4 + 3];
  double r00 = right[0 * 4 + 0];
  double r01 = right[0 * 4 + 1];
  double r02 = right[0 * 4 + 2];
  double r03 = right[0 * 4 + 3];
  double r10 = right[1 * 4 + 0];
  double r11 = right[1 * 4 + 1];
  double r12 = right[1 * 4 + 2];
  double r13 = right[1 * 4 + 3];
  double r20 = right[2 * 4 + 0];
  double r21 = right[2 * 4 + 1];
  double r22 = right[2 * 4 + 2];
  double r23 = right[2 * 4 + 3];
  double r30 = right[3 * 4 + 0];
  double r31 = right[3 * 4 + 1];
  double r32 = right[3 * 4 + 2];
  double r33 = right[3 * 4 + 3];
  out[0 * 4 + 0] = l00 * r00 + l01 * r10 + l02 * r20 + l03 * r30;
  out[0 * 4 + 1] = l00 * r01 + l01 * r11 + l02 * r21 + l03 * r31;
  out[0 * 4 + 2] = l00 * r02 + l01 * r12 + l02 * r22 + l03 * r32;
  out[0 * 4 + 3] = l00 * r03 + l01 * r13 + l02 * r23 + l03 * r33;
  out[1 * 4 + 0] = l10 * r00 + l11 * r10 + l12 * r20 + l13 * r30;
  out[1 * 4 + 1] = l10 * r01 + l11 * r11 + l12 * r21 + l13 * r31;
  out[1 * 4 + 2] = l10 * r02 + l11 * r12 + l12 * r22 + l13 * r32;
  out[1 * 4 + 3] = l10 * r03 + l11 * r13 + l12 * r23 + l13 * r33;
  out[2 * 4 + 0] = l20 * r00 + l21 * r10 + l22 * r20 + l23 * r30;
  out[2 * 4 + 1] = l20 * r01 + l21 * r11 + l22 * r21 + l23 * r31;
  out[2 * 4 + 2] = l20 * r02 + l21 * r12 + l22 * r22 + l23 * r32;
  out[2 * 4 + 3] = l20 * r03 + l21 * r13 + l22 * r23 + l23 * r33;
  out[3 * 4 + 0] = l30 * r00 + l31 * r10 + l32 * r20 + l33 * r30;
  out[3 * 4 + 1] = l30 * r01 + l31 * r11 + l32 * r21 + l33 * r31;
  out[3 * 4 + 2] = l30 * r02 + l31 * r12 + l32 * r22 + l33 * r32;
  out[3 * 4 + 3] = l30 * r03 + l31 * r13 + l32 * r23 + l33 * r33;
}