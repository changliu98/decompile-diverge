  g[18] = cd0; g[19] = cd1; g[20] = ce0; g[21] = ce1; g[22] = cf0; g[23] = cf1;
  g[24] = de0; g[25] = de1; g[26] = de2; g[27] = df0; g[28] = df1; g[29] = ef0;
