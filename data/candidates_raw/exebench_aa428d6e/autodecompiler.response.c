    ee2 += e[j+2]*e[j+2] + e[j+3]*e[j+3];
    ff0 += f[j]*f[j] + f[j+1]*f[j+1];
    ff1 += f[j]*f[j+1] + f[j+1]*f[j];
    gg0 += a[i]*a[i] + a[i+1]*a[i+1];
