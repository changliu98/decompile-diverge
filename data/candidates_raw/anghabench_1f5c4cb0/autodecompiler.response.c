unsigned long
ctz_64_v2 (unsigned long x)
{
  int n = 0;
  if ((x & 0xffffffff00000000) == 0) { n += 32; x <<= 32; }
  if ((x & 0xffff000000000000) == 0) { n += 24; x <<= 24; }
  if ((x & 0xff000000000000) == 0) { n += 16; x <<= 16; }
  if ((x & 0xf00000000000) == 0) { n += 8; x <<= 8; }
  if ((x & 0xc000000000) == 0) { n += 4; x <<= 4; }
  if ((x & 0x300000000000) == 0) { n += 2; x <<= 2; }
  if ((x & 0x2000000000000) == 0) { n += 1; }
  return n;
}