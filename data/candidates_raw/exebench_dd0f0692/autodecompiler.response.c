void mat4_invert(float* dst, float* b) {
    float inv[16];
    float det;

    inv[0] = b[5]*b[10]*b[15] - b[5]*b[11]*b[14] - b[9]*b[6]*b[15]
    + b[9]*b[7]*b[14] + b[13]*b[6]*b[11] - b[13]*b[7]*b[10];
    inv[4] = -b[4]*b[10]*b[15] + b[4]*b[11]*b[14] + b[8]*b[7]*b[15]
    - b[8]*b[6]*b[15] - b[12]*b[7]*b[10] + b[12]*b[6]*b[11];
    inv[8] = b[4]*b[9]*b[15] - b[4]*b[11]*b[13] - b[8]*b[5]*b[15]
    + b[8]*b[7]*b[13] + b[12]*b[5]*b[11] - b[12]*b[7]*b[9];
    inv[12] = -b[4]*b[9]*b[14] + b[4]*b[10]*b[13] + b[8]*b[5]*b[14]
    - b[8]*b[6]*b[13] - b[12]*b[5]*b[10] + b[12]*b[6]*b[9];
    inv[1] = -b[1]*b[10]*b[15] + b[1]*b[11]*b[14] + b[9]*b[2]*b[15]
    - b[9]*b[3]*b[14] - b[13]*b[2]*b[11] + b[13]*b[3]*b[10];
    inv[5] = b[0]*b[10]*b[15] - b[0]*b[11]*b[14] - b[8]*b[3]*b[15]
    + b[8]*b[2]*b[15] + b[12]*b[3]*b[10] - b[12]*b[2]*b[11];
    inv[9] = -b[0]*b[9]*b[15] + b[0]*b[11]*b[13] + b[8]*b[1]*b[15]
    - b[8]*b[3]*b[13] - b[12]*b[1]*b[11] + b[12]*b[3]*b[9];
    inv[13] = b[0]*b[9]*b[14] - b[0]*b[10]*b[13] - b[8]*b[1]*b[14]
    + b[8]*b[2]*b[13] + b[12]*b[1]*b[10] - b[12]*b[2]*b[9];
    inv[2] = b[1]*b[6]*b[15] - b[1]*b[7]*b[14] - b[5]*b[2]*b[15]
    + b[5]*b[3]*b[14] + b[13]*b[2]*b[7] - b[13]*b[3]*b[6];
    inv[6] = -b[0]*b[6]*b[15] + b[0]*b[7]*b[14] + b[4]*b[3]*b[15]
    - b[4]*b[2]*b[15] - b[12]*b[3]*b[6] + b[12]*b[2]*b[7];
    inv[10] = b[0]*b[5]*b[15] - b[0]*b[7]*b[13] - b[4]*b[1]*b[15]
    + b[4]*b[3]*b[13] + b[12]*b[1]*b[7] - b[12]*b[3]*b[5];
    inv[14] = -b[0]*b[5]*b[14] + b[0]*b[6]*b[13] + b[4]*b[1]*b[14]
    - b[4]*b[2]*b[13] - b[12]*b[1]*b[6] + b[12]*b[2]*b[5];
    inv[3] = -b[1]*b[6]*b[11] + b[1]*b[7]*b[10] + b[5]*b[2]*b[11]
    - b[5]*b[3]*b[10] - b[9]*b[2]*b[7] + b[9]*b[3]*b[6];
    inv[7] = b[0]*b[6]*b[11] - b[0]*b[7]*b[10] - b[4]*b[3]*b[11]
    + b[4]*b[2]*b[11] + b[8]*b[3]*b[6] - b[8]*b[2]*b[7];
    inv[11] = -b[0]*b[5]*b[11] + b[0]*b[7]*b[9] + b[4]*b[1]*b[11]
    - b[4]*b[3]*b[9] - b[8]*b[1]*b[7] + b[8]*b[3]*b[5];
    inv[15] = b[0]*b[5]*b[10] - b[0]*b[6]*b[9] - b[4]*b[1]*b[10]
    + b[4]*b[2]*b[9] + b[8]*b[1]*b[6] - b[8]*b[2]*b[5];

    det = b[0]*inv[0] + b[1]*inv[4] + b[2]*inv[8] + b[3]*inv[12];
    if (!det) {
        return;
    }
    det = 1.0 / det;

    for (int i = 0; i < 16; i++) {
        dst[i] = inv[i] * det;
    }
}