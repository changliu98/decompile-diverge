void copy_mat4f(float (*out)[4][4], float (*in)[4][4])
{
  (*out)[0][0] = (*in)[0][0];
  (*out)[0][1] = (*in)[1][0];
  (*out)[0][2] = (*in)[2][0];
  (*out)[0][3] = (*in)[3][0];
  (*out)[1][0] = (*in)[0][1];
  (*out)[1][1] = (*in)[1][1];
  (*out)[1][2] = (*in)[2][1];
  (*out)[1][3] = (*in)[3][1];
  (*out)[2][0] = (*in)[0][2];
  (*out)[2][1] = (*in)[1][2];
  (*out)[2][2] = (*in)[2][2];
  (*out)[2][3] = (*in)[3][2];
  (*out)[3][0] = (*in)[0][3];
  (*out)[3][1] = (*in)[1][3];
  (*out)[3][2] = (*in)[2][3];
  (*out)[3][3] = (*in)[3][3];
}