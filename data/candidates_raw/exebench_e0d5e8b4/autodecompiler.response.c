void foo(int x, float *y)
{
  int m;
  float wki, wdr, wdi, xr;

  wki = 0.7071067811865475244008443621048490392848359375f;
  m = x >> 1;
  if (m == 2) {
      wdr = wki * 0.38268343236508977172845998403039886676134765625f;
      wdi = wki * 0.923879532511286756128183189396788286826171875f;
      xr = wdi * y[3] + (0x80000000 ^ (wdr * y[1]));
      y[3] = wdr * y[3] + wdi * y[1];
      y[1] = xr;
  }
  y[m] *= wki;
}