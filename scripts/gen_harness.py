#!/usr/bin/env python3
"""Generate a function's driver (`source_code/harness.c`) from its signature.

`funcharness.py` parses the reference function's signature and emits a program that builds the
arguments from the bytes of one input file, calls the function, folds the return value and the
output buffers into a digest and writes the program's writable globals to `argv[2]`.

`funcharness_legacy.py` is the same generator before it gained literal seeds (an input file
that starts with a magic prefix is decoded as exact argument values, which is how a corpus's
own test inputs are fed in). The drivers frozen before that change and never re-frozen, among
them every AnghaBench driver, are reproduced only by the legacy version.

The remaining drivers were synthesized per function and cannot be regenerated by these scripts;
for them the driver in the bundle is the source:
  adapted    the generated driver with the argument-building section written for that function,
             where the generator cannot construct the arguments itself (structs, context
             pointers, `char **`): most GitHub drivers and some HumanEval and ExeBench ones
  separate   written on its own for the function: every CVE driver

  python3 scripts/gen_harness.py data/bundles/humaneval_000    # print the generated driver
  python3 scripts/gen_harness.py --check                       # regenerate every driver and
                                                               # compare with the shipped one
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from collections import Counter
from pathlib import Path

sys.dont_write_bytecode = True                       # keep the release free of __pycache__
HERE = Path(__file__).resolve().parent
BUNDLES = HERE.parent / "data" / "bundles"
GROUPS = ("humaneval", "exebench", "anghabench", "mbpp", "github_barebone", "cve_barebone")


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod                          # dataclasses resolve types via sys.modules
    spec.loader.exec_module(mod)
    return mod


GENERATORS = (("current", _load("funcharness")), ("legacy", _load("funcharness_legacy")))
ADAPTED, SEPARATE = "adapted", "separate"
# the state-dump helper every generated driver carries; an adapted driver keeps it
_GENERATED_HELPER = b"static void vb_dump(const char *path)"


def generate(bundle: Path, mod) -> bytes:
    """The driver `mod` generates for this bundle's reference function."""
    sig = mod.parse_signature((bundle / "target" / "original_function.c")
                              .read_text(errors="replace"))
    sig.name = json.loads((bundle / "target" / "meta.json").read_text())["name"]
    return mod.generate_harness(sig).encode("utf-8")


def origin(bundle: Path):
    """("current" | "legacy", generated bytes) if a generator reproduces the shipped driver
    byte for byte; else ("adapted" | "separate", None)."""
    shipped = (bundle / "source_code" / "harness.c").read_bytes()
    for label, mod in GENERATORS:
        try:
            out = generate(bundle, mod)
        except Exception:                            # signature this generator does not support
            continue
        if out == shipped:
            return label, out
    return (ADAPTED if _GENERATED_HELPER in shipped else SEPARATE), None


def out_of_generator(label: str) -> bool:
    return label in (ADAPTED, SEPARATE)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("bundles", nargs="*", help="bundle directories (default with --check: all)")
    ap.add_argument("--check", action="store_true",
                    help="compare the regenerated drivers with the shipped ones")
    args = ap.parse_args()

    if not args.check:
        if len(args.bundles) != 1:
            ap.error("give one bundle directory, or --check")
        label, out = origin(Path(args.bundles[0]))
        if out is None:
            print(f"{Path(args.bundles[0]).name}: the driver is {label}, not generator output",
                  file=sys.stderr)
            return 1
        sys.stdout.write(out.decode("utf-8"))
        return 0

    bundles = [Path(b) for b in args.bundles] or sorted(p for p in BUNDLES.iterdir() if p.is_dir())
    tally: Counter = Counter()
    broken = []
    for b in bundles:
        group = next((g for g in GROUPS if b.name.startswith(g + "_")), "?")
        label, _ = origin(b)
        tally[(group, label)] += 1
        # a bundle that declares a generated driver must be reproduced by one of the generators
        if out_of_generator(label) and \
                json.loads((b / "case.json").read_text()).get("harness") == "generated":
            broken.append(b.name)
    labels = ["current", "legacy", ADAPTED, SEPARATE]
    print(f"{'group':<17}" + "".join(f"{x:>10}" for x in labels))
    for g in [g for g in GROUPS if any(tally[(g, x)] for x in labels)]:
        print(f"{g:<17}" + "".join(f"{tally[(g, x)]:>10}" for x in labels))
    print(f"{'total':<17}" + "".join(f"{sum(v for (_, y), v in tally.items() if y == x):>10}"
                                     for x in labels))
    if broken:
        print(f"\n{len(broken)} generated drivers are NOT reproduced: {', '.join(broken[:10])}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
